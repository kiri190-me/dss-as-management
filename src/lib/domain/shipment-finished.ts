import type { RepairStatus } from "./types";

/**
 * ============================================================================
 * 「이 수리 건은 이미 나갔는가」 — 경보 넷이 함께 쓰는 한 잣대
 * ============================================================================
 * 함수 하나뿐인 파일이다. 그 하나를 위해 자리를 따로 내준 까닭이 둘 있다.
 *
 * ── ① 이것은 **알림의 개념이 아니다** ──────────────────────────────────────
 * 2026-10-30 까지 이 함수는 domain/notifications.ts 안에 살았다. 처음 쓰인 자리가
 * 「납기 임박」 알림이어서 그랬을 뿐, 묻는 것은 **출하 사실** 하나이고 지금 부르는
 * 자리는 알림 밖이 더 많다 — 수리 건 상세 화면, 내자 정리 목록, 조회 셋, 그리고
 * PO/내자 시스템의 사본까지다. 경보 넷(납기 임박 · 납기 지연 · 납기 역전 · 사내
 * 목표 출하일 미등록)이 「끝난 건」을 **같은 잣대**로 가르는 것이 이 함수의 일이라,
 * 그중 한 경보의 파일 안에 들어 있으면 자리가 거꾸로다.
 *
 * ── ② 🔴 고리(circular import)를 끊은 자리가 여기다 ───────────────────────
 * notifications.ts 와 due-date-inversion.ts 가 **서로를 보고 있었다**: 역전 판정이
 * 이 함수를 가져다 쓰고, 종 알림 한 줄이 역전 메모의 글자 상수
 * (DUE_DATE_INVERSION_NOTE)를 가져다 썼다. 그 고리는 **규율 하나**로만 버티고
 * 있었다 — 「저 상수를 모듈 최상위에서 읽지 마라」. 함수 밖으로 한 줄만 올리면
 * due-date-inversion.test.ts 가 통째로 ReferenceError 로 죽었다(초기화 전 바인딩).
 *
 * 이 함수를 여기로 옮기면서 사슬이 **한 방향**이 됐다:
 *
 *     notifications ──▶ due-date-inversion ──▶ shipment-finished
 *             └──────────────────────────────────────▶
 *
 * 🔴 **그래서 이 파일은 아무것도 들여오지 않는다 — `./types` 의 타입 하나뿐이다**
 * (그 types.ts 가 보는 것도 date-only.ts 하나다). 여기에 import 를 더하는 순간
 * 끊어 놓은 고리가 다른 모양으로 되살아날 수 있다. 사슬이 한 방향이라는 사실은
 * domain/shipment-finished.test.ts 가 **글자로** 지킨다 — 규율로만 버티던 것을
 * 시험이 무는 것으로 바꾼 것이 이 분가의 목적이다.
 *
 * ── 🔵 PO/내자 시스템에도 사본이 있다 ─────────────────────────────────────
 * dss-po 가 이 함수 하나만 떼어다 쓴다 — 그쪽도 **같은 이름 domain/shipment-finished.ts**
 * 다(2026-10-30 에 이 분가를 따라 함께 옮겼다. 그 전에는 저쪽도 domain/notifications.ts
 * 였는데, 그 이름은 애초에 **여기 있던 고리가 만든 이름**이었다). 🔴 저쪽에는 고리가
 * 없었고 지금도 없다 — 그래서 이름이 어긋나도 그쪽에서는 **아무것도 깨지지 않는다.**
 * 아래 함수 본문과 doc 주석은 그 사본과 **글자 하나까지 같아야**
 * 한다: 같은 건을 두 시스템이 다르게 가르면 A/S 화면에는 경보가 뜨는데 내자 정리
 * 에는 안 뜨는 날이 온다. 고칠 일이 생기면 두 저장소를 함께 고쳐라.
 * ============================================================================
 */

/**
 * 이 건은 이미 나갔는가 — **출하 완료된 건에는 「납기 임박」이 뜨지 않는다.**
 *
 * 보는 사실이 둘인 것은 isRepairCaseOverdue(types.ts)가 「납기 지연」을 가릴 때
 * 보는 바로 그 둘이기 때문이다. 상태 하나에만 기대면, 출하일은 찍혀 있는데
 * 워크플로 단계가 따라가지 못한 건에 「납기 임박」이 붙는 모순된 종이 된다. 두
 * 판정 다 역사적 기록이 아니라 **살아 있는 경보**라 같은 곳에서 빠져야 한다.
 *
 * `status` 가 `null` 일 수 있는 것은 workflow_steps.repair_status 가 아직
 * nullable 이기 때문이다(그 스키마 주석). 그런 건은 상태를 지어내지 않고 「아직
 * 안 나갔다」로 둔다 — 날짜가 임박했는데 조용히 빠지는 쪽보다 낫다.
 */
export function isRepairCaseShipmentFinished(row: {
  status: RepairStatus | null;
  actualShipmentDate: string | null;
}): boolean {
  if (row.status === "SHIPMENT_COMPLETED") return true;
  return row.actualShipmentDate !== null && row.actualShipmentDate.trim() !== "";
}
