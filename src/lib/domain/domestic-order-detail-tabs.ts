/**
 * ============================================================================
 * 「기타건 상세」의 주소들 (2026-11-06)
 * ============================================================================
 * 기타건 = **내자 정리의 한 줄**이고, 그중 수리 건이 붙지 않은 줄이다. 사용자가
 * 붙인 이름 그대로다 — 「그 상세창은 [기타건 상세]라고 부를께」.
 *
 * ── 왜 `/domestic-orders/{id}` 인가 ────────────────────────────────────
 * 이 화면이 보여 주는 것은 **내자 정리 표의 한 줄**이다. 목록이 `/domestic-orders`
 * 이므로 그 줄의 상세는 그 아래가 제자리고, 수리 건 상세(`/repair-cases/{id}`)와
 * **같은 모양**이라 탭 줄·활성 판정을 새로 짓지 않고 그대로 쓸 수 있다
 * (아래 resolveActiveTabHref 재사용).
 *
 * 따로 떼어 `/other-cases/{id}` 같은 이름을 두지 않은 까닭: 그러면 주소의 `id` 가
 * 가리키는 표가 무엇인지 주소만 봐서는 알 수 없고(실제로는 `domestic_orders.id`
 * 다), 나중에 그 줄에 수리 건을 이어 붙이는 순간 주소의 이름과 줄의 성격이
 * 어긋난다. 주소는 **어느 표의 어느 줄인가**만 말하게 두고, 「기타건」이라는 이름은
 * 화면이 쓴다.
 *
 * ── 🔴 주소는 권한과 무관하다 ───────────────────────────────────────────
 * 누가 어느 탭을 볼 수 있는지는 여기 두지 않는다 — 수리 건 쪽
 * (repair-case-detail-tabs.ts)이 같은 까닭으로 같은 모양이다. 주소는 언제나 같은
 * 곳을 가리키고, 볼 수 있는지는 레이아웃(그릴지 말지)과 각 페이지(막을지 말지)가
 * **따로** 판정한다.
 *
 * 반환 타입을 명시해 두는 것도 그쪽과 같은 이유다 — 호출부의 `.aproval` 같은
 * 오타가 화면에서가 아니라 tsc 에서 걸리게 한다.
 * ============================================================================
 */

/**
 * 🔴 **활성 탭을 고르는 규칙은 베끼지 않는다** — 수리 건 상세의 그 함수를 그대로
 * 부른다. 「가장 긴 앞가지가 이긴다」는 판단은 탭 줄이 있는 화면이면 어디서나 같고
 * (루트 탭의 주소가 나머지 전부의 접두사라 단순 `startsWith` 로는 모든 주소에서
 * 첫 탭이 켜진다), 한 벌 더 적으면 언젠가 한쪽만 고쳐진다. 이 파일에서 다시
 * 내보내는 것은 **부르는 쪽이 두 파일을 들여오지 않게** 하기 위해서다.
 */
export { resolveActiveTabHref } from "./repair-case-detail-tabs";

export type DomesticOrderDetailHrefs = {
  /** 루트(기본 정보). 🔴 **첫 화면**이고(사용자 결정), 나머지 셋의 문자열 접두사이기도 하다. */
  root: string;
  /** 이 줄에 연결된 견적서. 내용은 다음 조각에서 채운다. */
  quotes: string;
  /** 이 줄의 발주서. 내용은 다음 조각에서 채운다. */
  purchaseOrders: string;
  /** 검수/승인. 내용은 다음 조각에서 채운다. */
  approval: string;
};

export function domesticOrderDetailHrefs(domesticOrderId: string): DomesticOrderDetailHrefs {
  const root = `/domestic-orders/${domesticOrderId}`;
  return {
    root,
    quotes: `${root}/quotes`,
    purchaseOrders: `${root}/purchase-orders`,
    approval: `${root}/approval`,
  };
}
