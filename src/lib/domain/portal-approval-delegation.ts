/* ------------------------------------------------------------------ */

/**
 * 🔴 **안내 상자의 머리.** 「지금 확인할 수 없다」이지 **「없다」가 아니다**(파일
 * 머리말의 둘째 절). 둘을 같은 말로 적으면 맡긴 사람은 맡겨 뒀다고 믿고 대리인은
 * 왜 못 누르는지 끝내 모른다.
 */
export const PORTAL_DELEGATION_UNAVAILABLE_HEADLINE = "결재권 위임을 지금 확인할 수 없습니다";

/**
 * 🔴 **화면에 그대로 찍히는 글이다 — 주석 문체(별표)를 섞지 마라.**
 *
 * 🔵 앞 두 문장은 통합 승인함이 같은 상황에서 쓰는 말과 **거의 그대로**다
 * (dss-approvals/src/lib/approvals/delegation-view.ts 의 `delegationTroubles` —
 * 「통합 로그인 포털에 물어보지 못했습니다. 위임이 없는 것이 아니라 지금 읽지 못한
 * 것입니다.」). 같은 일이 두 화면에서 다른 낱말로 적히면, 두 곳을 오가는 사람은
 * 다른 종류의 고장으로 읽는다.
 *
 * 🔴 **뒤의 두 문장은 A/S 에만 있다.** 이 집에는 **제 위임 표가 따로 살아 있어서**
 * (설계 B-4 — 둘 다 살려 두기로 했다) 「어떤 사람은 멀쩡히 누르는데 어떤 사람만
 * 막힌다」가 실제로 일어난다. 그 까닭을 적어 두지 않으면 옆자리가 누르는 것을 보고
 * 자기 계정이 고장 난 줄 안다.
 */
export const PORTAL_DELEGATION_UNAVAILABLE_NOTICE =
  "통합 로그인 포털에 물어보지 못했습니다. 위임이 없는 것이 아니라 지금 읽지 못한 것입니다. " +
  "통합 승인함에서 맡긴 결재권으로는 지금 대신 누를 수 없으니, 잠시 뒤 새로고침해 주십시오. " +
  "본인의 결재와 이 시스템에서 직접 맡긴 위임은 그대로 처리됩니다.";

/**
 * 결재 **결과**가 「포털에 못 물었다」를 실어 왔으면, 서버가 돌려준 말 뒤에 그 사실을
 * 한 번 더 붙인다.
 *
 * ── 🔴 왜 이 자리가 필요한가 ───────────────────────────────────────────
 * 화면 위쪽의 안내 상자는 **화면을 그릴 때** 물어본 결과로 뜬다. 그런데 포털이
 * **그 뒤에** 넘어지면 상자는 안 떠 있고, 사람은 [승인]을 눌렀다가 「권한이 없습니다」
 * 만 받는다 — 바로 그 순간이 안내가 가장 필요한 때다. 그래서 `notePortalDelegationOutage`
 * 가 결과에 실어 보낸 칸을 **여기서 쓴다.** 🔴 이 함수가 없으면 그 칸은 아무도 안 읽는
 * 죽은 값이 된다.
 *
 * 🔵 한 줄로 잇는다(줄바꿈이 아니다) — 받는 자리들이 `<p>` 하나에 글자로 그리므로
 * 줄바꿈은 어차피 공백 한 칸으로 접힌다. 「보이는 대로」 적어 둔다.
 *
 * 🔵 깃발이 없으면 **받은 글자를 그대로** 돌려준다 — 포털이 멀쩡할 때는 아무 일도
 * 일어나지 않는다.
 */
export function appendPortalDelegationOutage(
  message: string,
  result: { portalDelegationUnavailable?: true }
): string {
  if (!result.portalDelegationUnavailable) return message;
  return `${message} ${PORTAL_DELEGATION_UNAVAILABLE_NOTICE}`;
}

/**
 * 결재 결과에 **「포털에 못 물은 채로 판정했다」**를 얹는다.
 *
 * ── 🔴 왜 결과에 싣나 ───────────────────────────────────────────────────
 * 설계 B-7 의 안내(「지금은 위임이 안 듣습니다」)를 띄우는 것은 **화면의 일**인데,
 * 화면이 그 사실을 알 길이 결과값밖에 없다. 여기서 싣지 않으면 안내를 붙이려는
 * 사람이 **결재 mutation 셋을 다시 열어야** 하고, 그때 셋 중 하나를 빠뜨리면
 * 「어떤 결재에서만 안내가 뜬다」가 된다.
 *
 * ── 🔴 성공·실패를 가리지 않는다 ────────────────────────────────────────
 * 막힌 쪽(FORBIDDEN)에 필요한 것은 분명하다 — 위임으로 통과했어야 할 사람이
 * 지정 관문에 막힌 그 순간이다. 성공한 쪽에도 그대로 싣는 까닭은 **가지를 두지
 * 않기 위해서**다: 「어느 때만 실린다」가 생기면 화면이 그 조건을 한 벌 더 적게
 * 되고, 두 벌이 갈리는 날 안내가 조용히 사라진다. 성공한 사람에게 보여 줄지는
 * 화면이 정한다(값이 있다고 반드시 띄워야 하는 것은 아니다).
 *
 * 🔵 못 물은 적이 없으면 **받은 값을 그대로 돌려준다** — 새 객체를 만들지 않으므로
 * 평소(포털이 멀쩡할 때)에는 아무 비용도 없다.
 */
export function notePortalDelegationOutage<T extends { portalDelegationUnavailable?: true }>(
  result: T,
  portal: PortalRouteDelegations
): T {
  if (!portal.unavailable) return result;
  return { ...result, portalDelegationUnavailable: true };
}
