/**
 * ============================================================================
 * 포털에 맡긴 결재권 위임 — 결재 길목이 받아 드는 모양 (순수)
 * ============================================================================
 * 2026-11-13 결정으로 결재권 위임을 **포털(dss-auth) 한 곳에 모으기로** 했다
 * (설계: dss-approvals/DELEGATION_DESIGN.md 의 B-1·B-2). 지정은 통합 승인함에서
 * 하고, 저장은 포털이 하고, **읽는 것은 각 시스템**이다. 이 파일은 A/S 가 그
 * 답을 들고 다니는 **그릇**이다 — 망도 DB 도 여기서 만지지 않는다.
 *
 * ── 🔴 왜 그릇이 따로 있나. 빈 목록과 「못 물었다」가 다르기 때문이다 ──────
 * 포털에 못 물었을 때 A/S 는 **「위임 없음」으로 보고 결재를 그대로 진행한다**
 * (설계 B-6). 포털 한 곳이 멈추면 세 시스템의 결재가 **전부** 멈추는 쪽이 더
 * 비싸다고 판단한 것이다. 🔴 **그 대가는 「대리인만 조용히 막힌다」**이고, 이
 * 저장소들에서 가장 비싼 결함 모양이 바로 그것이다. 그래서 설계 B-7 이 **눈에
 * 보이는 안내를 띄우라**고 못 박았다.
 *
 * 안내를 띄우려면 **「물어봤더니 없더라」와 「못 물었다」가 값에서 갈려 있어야**
 * 한다. 둘 다 `[]` 로 뭉개면 안내할 자리에서 구별할 길이 영영 없어진다. 그래서
 * 이 타입에 칸이 둘이다.
 *
 * ── 🔴 「포털 계정이 없다」는 **못 물은 것이 아니다** ────────────────────
 * A/S 는 포털과 이어지지 않은 로컬 계정을 허용한다(설계서 F-3). 그 사람은
 * `users.sso_subject` 가 비어 있어 포털에 물을 수가 없는데, 그때 `unavailable`
 * 은 **거짓**이다. 까닭은 장애가 아니라 **사실**이기 때문이다: 포털에 번호가 없는
 * 사람에게는 **포털 위임이 걸릴 수조차 없다**(승인함의 대리인 고르개는 포털
 * 사용자만 보여 준다). 「잠시 후 다시 시도해 주세요」라고 말하면 영영 오지 않을
 * 때를 기다리게 한다.
 *
 * ── 🔴 A/S 자신의 위임을 대신하지 않는다. 둘 다 산다 ────────────────────
 * 설계 B-4 로 **포털 위임과 각 시스템 위임을 둘 다 살려 두기로** 했다. 그래서 이
 * 값은 `approval_route_delegations`(A/S 제 표)를 읽은 결과에 **더해지는** 목록이고,
 * 합치는 자리는 domain/approval-route-delegation.ts 의 `actingApproverUserIds`
 * 하나다 — 「누를 수 있나」가 두 벌로 적히지 않게 하려는 그 함수의 원칙 그대로다.
 * ============================================================================
 */

/**
 * 포털에 물어본 결과. 🔴 **두 칸을 한 칸으로 줄이지 마라**(파일 머리말).
 */
export type PortalRouteDelegations = {
  /**
   * 포털이 「이 사람이 지금 대신할 수 있다」고 답한 결재권자들 — **A/S 의
   * `users.id`** 로 바꿔 둔 값이다.
   *
   * 🔴 포털이 주는 것은 **포털 번호(`sub`)** 이고, A/S 의 판정은 제 `users.id` 로
   * 돈다. 바꾸는 자리는 server/integration/portal-delegations.ts 한 곳이고,
   * **여기 들어오는 값은 이미 바뀐 뒤**다. 포털 번호를 그대로 넣으면 오류 없이
   * 영원히 아무도 못 누른다(domain/approval-route-delegation.ts 의 같은 경고).
   *
   * 🔵 **본인이 섞여 있어도 된다** — 포털은 답의 맨 앞에 부른 사람 자신을 넣어
   * 준다. 합치는 함수가 본인을 맨 앞에 두고 중복을 걷으므로 따로 빼지 않는다.
   */
  delegatorUserIds: readonly string[];
  /**
   * 🔴 **포털에 못 물었다**(죽었거나 · 느렸거나 · 우리를 거절했거나). 그때
   * `delegatorUserIds` 는 비지만, 그 빈 목록은 「없다」가 아니라 **「모른다」**다.
   *
   * 🔵 포털 계정이 없는 사람은 여기 해당하지 않는다 — 파일 머리말 참조.
   */
  unavailable: boolean;
};

/**
 * 🔴 **「이 결재에는 포털 위임을 묻지 않았다」를 글자로 적는 자리.**
 *
 * `{ delegatorUserIds: [], unavailable: false }` 를 그 자리에 바로 쓰면 「묻고 보니
 * 없었다」와 「아예 안 물었다」가 똑같이 생긴다. 이름을 붙여 두면 **왜 안 물었는지**를
 * 부르는 쪽 주석이 설명하게 된다(auth/approval-assignment.ts 의 NO_ROUTE_DELEGATIONS
 * 가 같은 까닭으로 같은 모양이다).
 *
 * 🔴 `unavailable` 이 **거짓**인 것에 뜻이 있다. 안 물은 것은 장애가 아니므로
 * 「포털을 확인하지 못했습니다」 안내가 뜨면 안 된다 — 뜨면 아무 상관없는 결재
 * 화면마다 경고가 깔린다.
 *
 * 지금 이 상수가 기본값으로 쓰이는 자리:
 *  · **수리 검수 승인** — 결재선을 탈 수 없어(표의 CHECK) 대신할 단계가 없다.
 *    서버 액션이 애초에 묻지 않는다(2초를 아끼는 자리이기도 하다).
 *  · 결재 mutation 을 **직접 부르는 시험·스크립트** — 망을 타지 않는다.
 */
export const NO_PORTAL_DELEGATIONS: PortalRouteDelegations = {
  delegatorUserIds: [],
  unavailable: false,
};

/**
 * 결재 결과에 **「포털에 못 물은 채로 판정했다」**를 얹는다.
 *
 * ── 🔴 왜 결과에 싣나 ───────────────────────────────────────────────────
 * 설계 B-7 의 안내(「지금은 위임이 안 듣습니다」)를 띄우는 것은 **화면의 일**인데,
 * 화면이 그 사실을 알 길이 결과값밖에 없다. 여기서 싣지 않으면 안내를 붙이려는
 * 사람이 **결재 mutation 셋을 다시 열어야** 하고, 그때 셋 중 하나를 빠뜨리면
 * 「어떤 결재에서만 안내가 뜬다」가 된다.
 *
 * ── 🔴 성공·실패를 가리지 않는다 ────────────────────────────────────────
 * 막힌 쪽(FORBIDDEN)에 필요한 것은 분명하다 — 위임으로 통과했어야 할 사람이
 * 지정 관문에 막힌 그 순간이다. 성공한 쪽에도 그대로 싣는 까닭은 **가지를 두지
 * 않기 위해서**다: 「어느 때만 실린다」가 생기면 화면이 그 조건을 한 벌 더 적게
 * 되고, 두 벌이 갈리는 날 안내가 조용히 사라진다. 성공한 사람에게 보여 줄지는
 * 화면이 정한다(값이 있다고 반드시 띄워야 하는 것은 아니다).
 *
 * 🔵 못 물은 적이 없으면 **받은 값을 그대로 돌려준다** — 새 객체를 만들지 않으므로
 * 평소(포털이 멀쩡할 때)에는 아무 비용도 없다.
 */
export function notePortalDelegationOutage<T extends { portalDelegationUnavailable?: true }>(
  result: T,
  portal: PortalRouteDelegations
): T {
  if (!portal.unavailable) return result;
  return { ...result, portalDelegationUnavailable: true };
}
