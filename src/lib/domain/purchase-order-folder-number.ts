import {
  normalizeShareFolderNameForCompare,
  sanitizeShareFolderNamePiece,
} from "./share-folder-naming";

/**
 * ============================================================================
 * **발주 건 폴더 이름에서 발주서번호를 읽는다** — 둘째 마디 (순수 — 파일시스템 없음) (2026-11-06)
 * ============================================================================
 * 같은 서류함(`<연도>/<고객사>/<발주 건>`)을 **기타건**(내자 정리의 한 줄)이 찾을 때 쓰는
 * 읽기다. 이웃(purchase-order-folder-name.ts)은 같은 이름에서 **날짜 · L/N · S/N** 을
 * 읽는데, 🔴 **기타건에는 L/N 도 S/N 도 없다** — 부속 · 케이블 · 일식처럼 장비가 아닌 줄이
 * 많아 그 길이 아예 안 통한다. 그래서 **번호로 찾는 길**이 따로 있다(사용자 결정 2026-11-06
 * — 「[발주서]는 내자정리에 적힌 [발주서 번호]를 통해서 발주서들을 찾도록 해줘」).
 *
 * ── 🔴 **앞 세 마디는 두 갈래가 같다** ───────────────────────────────────
 *   `101. 내자 20251223_PO4500371858_MBKK200-JS2_WN1183_1708076 - 16,720,000원`
 *    └순번┘└구분┘└─날짜─┘ └──PO번호──┘ └──모델──┘ └L/N┘ └─S/N─┘  └──금액──┘
 *   `117. 내자 20261103_PO261103031_(고객) 30kW 부속케이블 3SET - (금액)`
 *    └순번┘└구분┘└─날짜─┘ └─PO번호─┘ └──────────내용──────────┘  └금액┘
 * 뒤는 다르지만(수리 건은 모델_L/N_S/N, 기타건은 자유 글자) **둘째 마디가 번호**인 것은
 * 같다. 여기서 읽는 것은 그 한 마디뿐이다.
 *
 * ── 🔴 **번호 양식을 글자로 못 박지 않는다** ─────────────────────────────
 * 고객사마다 다르다 — `PO261103031`(9자리) · `PO4500361248` · `PO4500360904`(10자리 SAP
 * 꼴)가 실제로 함께 있다. 모양을 정규식으로 적으면 **새 고객사가 들어오는 날 조용히
 * 안 찾아진다**(오류가 아니라 「폴더가 없습니다」로 보여 아무도 신고하지 않는다). 그래서
 * 이 파일에는 `PO` 라는 글자도 자릿수도 없고, 둘째 마디를 **글자 그대로** 내보낸다 —
 * 맞대는 일은 부르는 쪽이 내자 줄에 적힌 번호와 **같은가**로만 한다.
 *
 * ── 🔴 **자리로 읽는다 — 이름 어딘가에 있는지 보지 않는다** ──────────────
 * 이웃이 L/N · S/N 을 **마지막 두 마디**로 읽는 것과 같은 규율이다. 폴더 이름 어딘가에
 * 번호 비슷한 글자가 있는지로 가르면, 첫 마디의 날짜(`20261103`)나 내용 마디에 적힌
 * 「…(PO261103031 건) 참고」 같은 글에 걸려 **남의 발주 건 폴더 안을 통째로** 보여 준다.
 * 이 자리는 폴더 하나의 안을 그대로 내미는 자리라 느슨한 쪽이 곧 사고다.
 *
 * ── 🔴 금액 꼬리(` - …`)는 **둘째 마디에서만** 뗀다 ──────────────────────
 * 꼬리는 **마지막 마디**에 붙는다. 마디가 셋 이상인 이름에서는 둘째 마디에 올 일이 없고,
 * 설명이 없어 마디가 둘뿐인 이름(`1. 내자 20261103_PO261103031 - 16,720,000원`)에서만
 * 둘째가 곧 마지막이라 붙는다. 그래서 **둘째 마디에서** 뗀다.
 *  · 🔴 이웃(purchase-order-folder-name.ts)의 금액 꼬리 규칙과 **같은 모양의 두 벌째**다.
 *    저쪽 것은 그 파일 안에만 있는(export 하지 않는) 상수이고, 🔴 **수리 건 길은 이 조각에서
 *    한 글자도 고치지 않는다**(느슨해지면 남의 발주서가 뜨는 모듈이라 일부러 엄격하다).
 *    그래서 꺼내 쓰는 대신 여기 한 번 더 적고, 두 벌이 **같은 꼬리를 뗀다**는 것을
 *    purchase-order-folder-number.test.ts 가 두 함수를 나란히 돌려 못 박는다.
 *  · 금액 모양을 글자로 적지 않는 것도 저쪽과 같다 — 원화 · 외화 · 메모 무엇이 붙든
 *    **띄어쓴 하이픈** 뒤는 번호가 아니다. 그래서 번호 안의 하이픈(`PO-2026-001`)이나
 *    모델 이름의 하이픈은 떨어지지 않는다.
 *
 * ── 🔴 **글자 다루기는 공용 함수를 쓴다** ────────────────────────────────
 * 사람이 탐색기 · NAS 에서 만든 폴더라 한글이 풀어쓴(NFD) 모양이거나 공백이 두 칸일 수
 * 있다. 비교용 다듬기(NFC · 연속 공백)는 share-folder-naming.ts 한 벌이다 — 여기에 두
 * 벌째 적지 않는다(이웃도 그 한 벌을 쓴다).
 *
 * 🔴 순수하다 — fs · 통로 · 서버 · DB 가 한 글자도 없다.
 * ============================================================================
 */

/**
 * 마디 끝에 붙는 금액 꼬리 — ` - 16,720,000원`. 🔴 **금액 모양을 글자로 적지 않는다**(머리말).
 */
const AMOUNT_TAIL = /\s-\s[\s\S]*$/;

/**
 * 발주 건 폴더 이름의 **둘째 마디**를 그대로 돌려준다. 읽지 못하면 null 이고, 그 폴더는
 * 후보에서 빠진다 — 🔴 **반쯤 읽어 「아마 이것일 것」을 내놓지 않는다**(이웃 머리말과 같은
 * 규율). 마디가 둘보다 적은 이름(`임시 발주서 및 신용장 - 바로 가기`)도 여기서 null 이다.
 */
export function readPurchaseOrderFolderNumber(folderName: string): string | null {
  if (typeof folderName !== "string") return null;
  const pieces = normalizeShareFolderNameForCompare(folderName).split("_");
  // 번호는 둘째 마디다 — 날짜 마디 하나 + 번호, 적어도 둘이어야 자리로 읽을 수 있다.
  if (pieces.length < 2) return null;

  const number = pieces[1].replace(AMOUNT_TAIL, "").trim();
  return number === "" ? null : number;
}

/**
 * 번호 하나를 **비교용 열쇠**로 만든다 — 다듬고(금지 글자 · 연속 공백 · NFC) 대소문자를
 * 접는다. 못 쓸 값이면 null 이다.
 *
 * 🔴 **디스크의 폴더 이름과 내자 줄에 적힌 번호가 이 한 함수를 함께 쓴다.** 한쪽만 손으로
 * 다듬으면 NFD 로 앉은 폴더나 소문자로 적힌 번호가 조용히 안 맞게 된다.
 *
 * 🔴 **글자나 숫자가 한 자라도 있어야 한다** — 내자 정리에는 `-` 한 글자만 적힌 칸이 있다.
 * 그 값을 열쇠로 쓰면 둘째 마디가 `-` 인 아무 폴더에나 걸린다(이웃의 isUsableKey 와 같은
 * 까닭 · 같은 잣대).
 *
 * 로케일을 `en-US` 로 못 박는 것도 공용 모듈 · 이웃과 같다(터키어 로케일에서 `i` 가 다른
 * 글자가 되지 않게).
 */
export function purchaseOrderNumberKey(value: string | null | undefined): string | null {
  const key = sanitizeShareFolderNamePiece(value).toLocaleUpperCase("en-US");
  return /[\p{L}\p{N}]/u.test(key) ? key : null;
}
