/**
 * ============================================================================
 * 🔴 엑셀 열 너비(문자 단위) → **픽셀** — 문서와 화면이 **같은 식**으로 센다
 * ============================================================================
 * 이 셈이 **두 벌**이었다(2026-11-27 에 합쳤다):
 *
 *   문서 쪽  `xlsx/sheet-print-grid.ts` 의 `charsToPixels` — 규격 그대로,
 *            **열마다** 픽셀을 내고 **버린다**(`Math.trunc`).
 *   화면 쪽  `domain/service-report-body-wrap.ts` 의 `serviceReportColumnWidthPx`
 *            — 범위의 열 너비를 **다 더한 뒤** `Math.round(합 × 8)` 했다.
 *
 * 🔴 **두 식은 열 너비가 `1.875` 일 때만 우연히 같았다**(둘 다 15px/열). Excel 이
 * 양식을 저장하면서 열 너비를 `1.90625` → `1.9296875` 로 다시 쓴 뒤로는 갈라졌고
 * (본문 `H:AU` 40열: 문서 600px · 화면 618px), **아무 오류도 안 났다.** 미리보기가
 * 문서보다 3% 넓게 그리고 있었고, 같은 식을 쓰는 채우개는 한 줄에 86칸을 담을 수
 * 있다고 믿으며 실제로는 84칸짜리 칸에 썼다.
 *
 * 그래서 식을 **여기 하나로** 모으고 양쪽이 이것을 부른다. 베껴 적으면 다음에
 * 한쪽만 고쳐져 또 갈라진다 — 이 저장소가 이미 그 사고를 겪었다.
 *
 * ── 🔴 왜 «열마다» 버리는가 ─────────────────────────────────────────────
 * Excel 은 열을 **하나씩** 픽셀로 바꾸고 소수를 버린다. 그래서 40열의 폭은
 * 「합을 한 번 환산한 값」이 아니라 「환산한 값을 40번 더한 값」이다:
 *
 *   열 너비 1.9296875 → 15px,  × 40열 = **600px**   ← 문서가 그리는 값
 *   합 77.1875 × 8 = 617.5 → 반올림 618px             ← 화면이 그리던 값
 *
 * 버림이 열마다 일어나므로 열 너비가 조금 달라져도 픽셀은 **그대로일 수 있다** —
 * `1.875`·`1.90625`·`1.9296875` 는 셋 다 15px 이다. 「양식이 넓어졌다」가 곧
 * 「문서가 넓어졌다」가 아니다.
 *
 * ── 🔴 이 파일은 순수하다 ───────────────────────────────────────────────
 * `server-only` · `node:*` · React · DB 를 물지 않는다. 그래야 브라우저로 가는
 * 화면 코드와 zip 을 읽는 서버 코드가 **같은 함수**를 부를 수 있다.
 * ============================================================================
 */

/**
 * 🔴 열 너비의 «문자 단위»를 픽셀로 바꿀 때 쓰는 **최대 숫자 폭**.
 *
 * OOXML 의 환산식은 규격에 있다:
 *
 *     pixels = Truncate(((256 × width + Truncate(128 ÷ MDW)) ÷ 256) × MDW)
 *
 * `MDW` 는 통합문서 기본 글꼴에서 숫자 한 자가 차지하는 픽셀 수다. 규격은 값을
 * 파일에 적어 두지 않으므로 어딘가에서 알아내야 한다.
 *
 * **이 양식의 값은 8이고, 양식 스스로가 그것을 알려 주었다.** 그림 앵커에는 셀
 * 좌표(`<xdr:from>`)와 절대 좌표(`<a:off>`)가 함께 적혀 있어서 둘을 견주면
 * 열 너비의 실제 픽셀 값이 나온다(실측):
 *
 *   · 「그림 4」 from = 33열 + 11px, a:off.x = 484px → 1~32열 = 473px
 *   · 「그림 6」 from = 43열 +  9px, a:off.x = 632px → 1~42열 = 623px
 *   → 33~42열(너비 1.875) 10칸 = 150px → 15px/칸,  너비 1.75 는 14px/칸
 *   → 위 식에 MDW=8 을 넣으면 정확히 15 와 14 가 나온다(MDW=7 이면 13 과 12).
 *
 * 이 값은 통합문서의 **기본 글꼴**(표준 스타일 = ＭＳ Ｐゴシック 11pt)이 정한다.
 *
 * 🔴 **2026-10-19 — 위 실측은 양식에서 사라졌다.** 사용자가 도장을 바꿔 저장한
 * 뒤로 두 도장의 `<a:off>` 가 한 칸을 15px 이 아니라 13.913px 로 잡은 격자로 다시
 * 적혔다(세로도 어긋나 있어 그 값은 «마지막으로 그린 기계의 캐시»다 — 역산하면
 * 숫자 한 자를 ≈7.04px 로 쟀고, 선언된 기본 글꼴이 그 PC 에 없어 대체되면 그렇게
 * 된다). 그래서 시험(`xlsx/sheet-print-grid.test.ts`)은 이제 **절대 크기 대신**
 * ①앵커들이 배율 하나로 설명되는가(격자의 모양) ②기본 글꼴이 그대로인가(이 상수의
 * 근거)를 본다. 자세한 셈과 까닭은 그 시험의 머리말에 적어 두었다.
 *
 * ⚠️ 글꼴이 바뀐 양식이 오면 폭이 몇 % 어긋난다. 그래도 **비율은 열끼리 그대로**
 * 유지되고(같은 식을 모든 열에 쓰므로) 화면은 종이에 맞춰 다시 줄이므로,
 * 어긋나 봐야 문서가 조금 좁거나 넓게 보일 뿐 자리가 무너지지는 않는다.
 */
export const EXCEL_MAX_DIGIT_WIDTH_PX = 8;

/**
 * 열 **하나**의 너비(문자 단위) → 픽셀. 96dpi 기준이라 CSS 픽셀과 1:1 이다.
 *
 * 🔴 **열 하나씩 부를 것.** 범위의 너비를 다 더한 뒤 한 번 부르면 버림이 한 번만
 * 일어나 문서와 어긋난다(머리말의 「왜 열마다 버리는가」). 범위는
 * `excelColumnRangePx` 가 센다.
 */
export function excelColumnWidthPx(chars: number): number {
  const mdw = EXCEL_MAX_DIGIT_WIDTH_PX;
  return Math.trunc(((256 * chars + Math.trunc(128 / mdw)) / 256) * mdw);
}

/**
 * 열 너비 여러 개(왼쪽부터) → 그 범위의 픽셀 폭.
 *
 * 🔴 더하는 것은 **픽셀**이다 — 너비를 먼저 더하면 안 된다. 인자가 비면 0 이다
 * (범위가 비었다는 뜻이고, 그것을 폭으로 쓸지 거절할지는 부르는 쪽이 정한다).
 */
export function excelColumnRangePx(widths: readonly number[]): number {
  return widths.reduce((sum, width) => sum + excelColumnWidthPx(width), 0);
}
