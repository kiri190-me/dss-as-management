/**
 * 실행 화면 **아래 목록**을 어떻게 접는가. 순수 함수만 — DOM 도 React 도 DB 도
 * 건드리지 않는다(procedure-execution-focus.ts 와 같은 규약).
 *
 * ──────────────────────────────────────────────────────────────────────
 * 왜 접는가
 * ──────────────────────────────────────────────────────────────────────
 * 실행 화면은 노드 카드를 네 구역(실행 가능·진행 중·차단됨·완료/건너뜀)에
 * 평평하게 깔아 놓는다. 카드 한 장마다 단추 넷과 작업 메모 칸이 **전부 펼쳐져**
 * 있어서, 22장짜리 절차에서는 화면이 끝없이 길어진다.
 *
 * 그 길이를 줄여도 되는 근거가 이번에 생겼다 — 맨 위에 「지금 할 일」 큰 카드
 * (procedure-execution-focus.ts)와 「지금 어디쯤인가」 띠
 * (procedure-execution-minimap.ts)가 섰다. 지금 해야 할 한 장과 그 둘레는 접지
 * 않은 채로 늘 보이므로, **나머지 목록은 평소에 접혀 있어도 일이 막히지 않는다.**
 *
 * ──────────────────────────────────────────────────────────────────────
 * 왜 네 구역을 **둘**로 담는가
 * ──────────────────────────────────────────────────────────────────────
 * 구역 넷을 각각 접으면 접는 줄이 넷 생겨서, 줄인 길이만큼 줄 머리가 늘어난다.
 * 사람이 아래 목록을 여는 까닭은 둘뿐이다 — 「아직 남은 것이 뭐지」와 「아까 뭘
 * 했더라」. 그래서 그 둘로 담는다:
 *
 *   - 전체 단계 보기 … 아직 안 끝난 것(대기 · 진행 중 · 차단됨)
 *   - 지나온 길     … 끝난 것(완료 · 건너뜀)
 *
 * ──────────────────────────────────────────────────────────────────────
 * 🔴 접으면 안 되는 때가 셋 — 그래서 이 판정이 순수 함수다
 * ──────────────────────────────────────────────────────────────────────
 * 화면 안에 if 로 흩어 두면 나중에 한쪽만 고치게 된다. 셋 다 **개발 DB 에 실제로
 * 있는 상태**다(2026-11-02 실측: 실행 4건 중 하나는 28장이 전부 완료라 지금 할
 * 일이 없고, 둘은 차단됨이 하나씩 있다). 꾸며낸 가정이 아니다.
 *
 *   1. 지금 할 일이 없을 때(NO_CURRENT_TASK) — 위의 큰 카드가 안 서는 자리라,
 *      접힌 줄만 남으면 화면에 손댈 것이 하나도 안 보인다.
 *   2. 차단됨이 하나라도 있을 때(HAS_BLOCKED) — 사람이 사유를 적어 막아 둔
 *      것이다. 접어서 감추면 막아 둔 뜻이 화면에서 지워지고, 절차가 왜 안
 *      흐르는지 아무 데도 안 적혀 있게 된다.
 *   3. 남은 것이 한 장도 없을 때(ALL_FINISHED) — 이때는 **「지나온 길」쪽**을
 *      펼친다. 다 끝난 실행에서 볼 것은 「무엇을 했는가」뿐이다.
 *
 * 까닭까지 돌려주는 것은 pickCurrentTask 와 같은 뜻이다 — 참·거짓 하나만
 * 돌려주면 시험이 「펼쳐졌다」까지만 재고 **어느 까닭으로** 펼쳐졌는지는 못 잰다.
 *
 * ──────────────────────────────────────────────────────────────────────
 * 🔴 담을 카드가 없는 묶음은 **아예 안 그린다**(null)
 * ──────────────────────────────────────────────────────────────────────
 * 처음에는 1번만 보고 「지금 할 일이 없으면 전체 단계 보기를 펼친다」로 적었는데,
 * 실측 dd0389d1(27장이 전부 완료)에서 **정반대로** 작동했다 — 비어 있는
 * 「전체 단계 보기 (0)」이 펼쳐져 「…없습니다」 세 줄을 보이고, 정작 27장이 든
 * 「지나온 길」은 접혀 있었다. 접는 까닭이 길이를 줄이는 것인데 빈 묶음이 자리를
 * 먹으면 거꾸로다.
 *
 * 그래서 규칙을 하나 더 두되 **두 묶음에 똑같이** 적용한다 — 머릿수가 0 이면
 * 그 묶음은 null 이고, 화면은 그 자리에 아무것도 안 그린다. 한쪽에만 두면
 * 「전체 단계 보기는 숨고 지나온 길 (0)은 남는」 비대칭이 생기고, 시작 직후
 * (끝낸 것이 0장)에 또 빈 줄 하나가 남는다. 노드가 아예 없는 실행에서는 둘 다
 * null 이라 목록 자리가 통째로 사라진다.
 *
 * 🔵 「아무것도 안 남았다」는 사실은 요약 카드의 「27 / 27 · 끝」과 큰 카드
 * 자리의 안내(「모든 작업이 끝났습니다」)가 이미 말한다 — 묶음을 숨겨도 그 말은
 * 안 사라진다.
 *
 * 참·거짓(`hidden: true`)이 아니라 **null** 로 돌려주는 까닭: 숨길 묶음에는
 * 그릴 글자가 없는데 `hidden` 으로 두면 「전체 단계 보기 (0)」이라는 **틀린
 * 글자가 값 안에 남는다.** 누군가 그 플래그를 안 보고 그리면 그대로 화면에
 * 뜬다. null 이면 타입이 「이 경우를 처리하라」고 강제한다.
 *
 * 🔴 「지금 할 일이 있는가」를 여기서 다시 판정하지 않는다. pickCurrentTask 가
 * 정한 결과를 인자로 받는다 — 두 벌로 두면 큰 카드는 서 있는데 목록은 「없다」고
 * 보고 펼치는 날이 오고, 타입이 같아 컴파일러는 아무 말도 안 한다.
 *
 * ──────────────────────────────────────────────────────────────────────
 * 괄호 안 수는 **화면의 네 구역 머릿수의 합**이어야 한다
 * ──────────────────────────────────────────────────────────────────────
 * 화면은 같은 배열(executionDetail.nodes)을 status 로 걸러 네 구역을 만든다.
 * 여기서도 **같은 배열을 같은 기준으로** 센다. 특히 「지금 할 일」로 위에 올라간
 * 한 장을 빼지 않는다 — 그 노드는 목록에서 사라지지 않고 **점선 한 줄**로 남아
 * 있으므로(ProcedureExecutionScreen 의 NodeSection), 빼면 접힌 줄의 수가 실제로
 * 보이는 줄 수보다 한 장 모자라게 된다.
 *
 * ──────────────────────────────────────────────────────────────────────
 * 접힌 줄에 덧말을 붙이는 까닭
 * ──────────────────────────────────────────────────────────────────────
 * 펼치지 않고도 알아야 할 것이 구역마다 하나씩 있다.
 *
 *   - 전체 단계 보기 … 차단됨 수. 위 2번으로 펼쳐 두기는 하지만 사람이 다시
 *     접을 수 있다(<details> 는 눌러서 닫힌다). 접힌 뒤에도 「막힌 것이 있다」가
 *     줄에 남아야 한다.
 *   - 지나온 길 … 건너뛴 수. 건너뜀은 **안 한 일**이라 완료와 뜻이 다르다.
 *     둘을 합쳐 「6」으로만 적으면 「여섯 개 했다」로 읽힌다.
 */

import type { ProcedureCaseExecutionNodeStatus } from "./procedure-case-execution-types";

export type FoldCandidate = { status: ProcedureCaseExecutionNodeStatus };

/** 접지 않고 펼친 채로 두는 까닭. 접혀 있으면 null. */
export type ExecutionFoldOpenReason =
  /** 「지금 할 일」 큰 카드가 안 서는 자리다 — 접으면 손댈 것이 하나도 안 보인다. */
  | "NO_CURRENT_TASK"
  /** 사람이 사유를 적어 막아 둔 것이 있다 — 감추면 절차가 왜 안 흐르는지 안 적힌다. */
  | "HAS_BLOCKED"
  /**
   * 남은 것이 한 장도 없다. 🔴 이 까닭은 **「지나온 길」쪽에만** 붙는다 —
   * 그때 「전체 단계 보기」는 담을 카드가 없어 아예 안 그려진다(null).
   */
  | "ALL_FINISHED";

export type ExecutionFoldNote = {
  text: string;
  /**
   * ATTENTION 은 「눈에 띄어야 하는 것」(차단됨), MUTED 는 「알아 두면 되는
   * 것」(건너뜀). 색 이름을 여기 적지 않는 까닭은 이 파일이 화면을 모르기
   * 때문이다 — 무엇이 더 급한지만 정하고, 어떤 색인지는 컴포넌트가 정한다.
   */
  tone: "ATTENTION" | "MUTED";
};

export type ExecutionFoldGroup = {
  /** 접힌 줄에 그대로 뜨는 글자. 괄호 안 수까지 한 덩이다. */
  summary: string;
  /** 이 묶음이 담는 카드 수 = 화면 구역 머릿수의 합. */
  count: number;
  open: boolean;
  openReason: ExecutionFoldOpenReason | null;
  /** 제목 줄에 덧붙는 한 마디. 없으면 null — 그리는 쪽이 아무것도 안 그린다. */
  note: ExecutionFoldNote | null;
};

export type ExecutionListFold = {
  /**
   * 아직 안 끝난 것 — 대기 · 진행 중 · 차단됨.
   * 🔴 한 장도 없으면 null — 화면은 그 자리에 **아무것도 안 그린다**(위 머리말).
   */
  remaining: ExecutionFoldGroup | null;
  /** 끝난 것 — 완료 · 건너뜀. 역시 한 장도 없으면 null. */
  done: ExecutionFoldGroup | null;
};

/**
 * 아래 목록 두 묶음의 머릿수 · 덧말 · **펼친 채로 둘지**를 한 번에 정한다.
 *
 * `nodes` 에는 화면이 네 구역을 만들 때 쓰는 **그 배열을 그대로** 준다
 * (executionDetail.nodes). 걸러서 주면 괄호 안 수가 화면과 어긋난다.
 */
export function buildExecutionListFold(input: {
  nodes: readonly FoldCandidate[];
  /** pickCurrentTask 가 하나를 골랐는가. 여기서 다시 고르지 않는다(위 머리말). */
  hasCurrentTask: boolean;
}): ExecutionListFold {
  const countOf = (status: ProcedureCaseExecutionNodeStatus) => input.nodes.filter((n) => n.status === status).length;

  const blocked = countOf("BLOCKED");
  const skipped = countOf("SKIPPED");
  const remainingCount = countOf("PENDING") + countOf("IN_PROGRESS") + blocked;
  const doneCount = countOf("COMPLETED") + skipped;

  // 🔴 까닭의 차례가 뜻을 가진다. 둘 다 해당하면(= 남은 것이 전부 차단됨)
  // 「지금 할 일이 없다」가 더 큰 사정이다 — 그때 큰 카드 자리에 서는 안내가
  // 「아래 「차단됨」에서 [재개(되돌림)]로 풀어야」라고 아래를 가리키므로,
  // 가리킨 곳이 접혀 있으면 안 된다.
  //
  // 남은 것이 0 장인 경우는 여기 안 적는다 — 그 묶음은 아예 안 그려지므로
  // (아래 null) 「왜 펼쳤나」를 따질 자리가 없다.
  const remainingOpenReason: ExecutionFoldOpenReason | null = !input.hasCurrentTask
    ? "NO_CURRENT_TASK"
    : blocked > 0
      ? "HAS_BLOCKED"
      : null;

  // 남은 것이 한 장도 없으면 지금 볼 것은 「무엇을 했는가」뿐이다. 그때만
  // 지나온 길을 펼친다 — 할 일이 남아 있는데 끝난 것을 펼치면, 줄이려던 길이가
  // 그대로 돌아오고 지금 할 일이 아래로 밀린다.
  const allFinished = remainingCount === 0;

  return {
    remaining:
      remainingCount === 0
        ? null
        : {
            summary: `전체 단계 보기 (${remainingCount})`,
            count: remainingCount,
            open: remainingOpenReason !== null,
            openReason: remainingOpenReason,
            note: blocked > 0 ? { text: `차단됨 ${blocked}`, tone: "ATTENTION" } : null,
          },
    done:
      doneCount === 0
        ? null
        : {
            summary: `지나온 길 (${doneCount})`,
            count: doneCount,
            open: allFinished,
            openReason: allFinished ? "ALL_FINISHED" : null,
            note: skipped > 0 ? { text: `건너뜀 ${skipped}`, tone: "MUTED" } : null,
          },
  };
}
