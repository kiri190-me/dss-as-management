/**
 * 실행 화면 **아래 목록**을 어떻게 접는가. 순수 함수만 — DOM 도 React 도 DB 도
 * 건드리지 않는다(procedure-execution-focus.ts 와 같은 규약).
 *
 * ──────────────────────────────────────────────────────────────────────
 * 왜 접는가
 * ──────────────────────────────────────────────────────────────────────
 * 실행 화면은 노드 카드를 네 구역(실행 가능·진행 중·차단됨·완료/건너뜀)에
 * 평평하게 깔아 놓는다. 카드 한 장마다 단추 넷과 작업 메모 칸이 **전부 펼쳐져**
 * 있어서, 22장짜리 절차에서는 화면이 끝없이 길어진다.
 *
 * 그 길이를 줄여도 되는 근거가 이번에 생겼다 — 맨 위에 「지금 할 일」 큰 카드
 * (procedure-execution-focus.ts)와 「지금 어디쯤인가」 띠
 * (procedure-execution-minimap.ts)가 섰다. 지금 해야 할 한 장과 그 둘레는 접지
 * 않은 채로 늘 보이므로, **나머지 목록은 평소에 접혀 있어도 일이 막히지 않는다.**
 *
 * ──────────────────────────────────────────────────────────────────────
 * 🔴 묶음이 **둘에서 하나**로 줄었다(2026-11-02, 조각 8)
 * ──────────────────────────────────────────────────────────────────────
 * 전에는 네 구역을 둘로 담았다 — 「전체 단계 보기」(아직 안 끝난 것)와 「지나온
 * 길」(완료·건너뜀). 사용자가 눈으로 보고 정했다:
 *
 *   「[실행 이력]과 [지나온 길]이 겹치는 내용들이 있는 것 같으니까
 *    [실행 이력]에 [지나온 길]의 내용을 넣자.」
 *
 * 겹치는 것이 맞다 — 「지나온 길」은 끝난 노드의 **카드**(작업 메모 · 건너뛴 사유)
 * 이고 「실행 이력」은 그 일들의 **시각 기록**(누가 언제)이다. 같은 일을 두 묶음이
 * 각자 적고 있었다. 그래서 「지나온 길」 묶음을 없애고 그 카드를 「실행 이력」
 * 묶음 **안**으로 옮겼다(아래 buildExecutionHistoryFold).
 *
 * 🔴 **버린 것은 하나도 없다.** 카드 쪽의 작업 메모·건너뛴 사유·차단 사유도,
 * 이력 쪽의 누가 언제도 그대로 남는다 — 담는 그릇만 하나로 줄었다.
 *
 * 그래서 이 함수가 돌려주는 것은 이제 「전체 단계 보기」 하나다.
 *
 * ──────────────────────────────────────────────────────────────────────
 * 🔴 「전체 단계 보기」는 **언제나 접혀 있다**(2026-11-02 사용자 결정)
 * ──────────────────────────────────────────────────────────────────────
 * 처음에는 접으면 안 되는 때를 둘 뒀다 — 지금 할 일이 없을 때와 차단됨이 있을
 * 때. 눈으로 보고 **되돌렸다**: 길이를 줄이려고 접는 묶음인데 평소 화면에서
 * 자꾸 펼쳐져 있어서, 접기가 거의 듣지 않았다. 사람이 필요하면 한 번 누르면
 * 열린다.
 *
 * 🔵 그래도 **「차단됨 N」 딱지는 제목 줄에 남는다**(아래 note). 접혀 있어도
 * 막힌 것이 있다는 사실은 화면에서 안 사라져야 한다 — 펼쳐 두는 것이 아니라
 * **제목에 적는 것**으로 그 요구를 지킨다.
 *
 * ──────────────────────────────────────────────────────────────────────
 * 🔴 **마친 실행**에서는 「전체 단계 보기」를 아예 안 그린다
 * ──────────────────────────────────────────────────────────────────────
 * 끝까지 안 가고 [절차 끝내기]를 눌러도 마친 것이다. 그런데 남은 카드 열몇 장이
 * 그대로 떠 있으면 마친 것처럼 보이지 않는다(2026-11-02 눈 확인). 사람이
 * 「마쳤다」고 했으면 **남은 것은 화면에서 물러난다** — 지운 것이 아니라 안
 * 그리는 것이고, 무엇이 남았는지는 「이 건의 다른 절차」 줄의 진행도가 그대로
 * 말한다(마친 실행의 요약 상자는 그 줄로 내려갔다 — 조각 8).
 *
 * 「지나온 길」의 카드는 그때도 남는다 — 「실행 이력」 묶음 안에서. 마친 뒤 볼
 * 것이 그것이다.
 *
 * ──────────────────────────────────────────────────────────────────────
 * 🔴 담을 카드가 없는 묶음은 **아예 안 그린다**(null)
 * ──────────────────────────────────────────────────────────────────────
 * 처음에는 「지금 할 일이 없으면 전체 단계 보기를 펼친다」로 적었는데(그 규칙
 * 자체는 지금 없어졌다 — 위 머리말), 실측 dd0389d1(27장이 전부 완료)에서
 * **정반대로** 작동했다 — 비어 있는
 * 「전체 단계 보기 (0)」이 펼쳐져 「…없습니다」 세 줄을 보이고, 정작 27장이 든
 * 「지나온 길」은 접혀 있었다. 접는 까닭이 길이를 줄이는 것인데 빈 묶음이 자리를
 * 먹으면 거꾸로다.
 *
 * 그 규칙은 지금 **두 묶음에 똑같이** 적용된다 — 「전체 단계 보기」도, 「실행
 * 이력」도 담을 것이 없으면 null 이고, 화면은 그 자리에 아무것도 안 그린다.
 *
 * 참·거짓(`hidden: true`)이 아니라 **null** 로 돌려주는 까닭: 숨길 묶음에는
 * 그릴 글자가 없는데 `hidden` 으로 두면 「전체 단계 보기 (0)」이라는 **틀린
 * 글자가 값 안에 남는다.** 누군가 그 플래그를 안 보고 그리면 그대로 화면에
 * 뜬다. null 이면 타입이 「이 경우를 처리하라」고 강제한다.
 *
 * 🔴 「마쳤는가」를 여기서 다시 판정하지 않는다 — 큰 카드(pickCurrentTask)와
 * **같은 사실**을 인자로 받는다. 두 벌로 두면 큰 카드는 물러났는데 목록만 남는
 * 날이 오고, 타입이 같아 컴파일러는 아무 말도 안 한다.
 *
 * ──────────────────────────────────────────────────────────────────────
 * 괄호 안 수는 **화면이 그 묶음에 담는 것의 수**여야 한다
 * ──────────────────────────────────────────────────────────────────────
 * 화면은 같은 배열(executionDetail.nodes)을 status 로 걸러 네 구역을 만든다.
 * 여기서도 **같은 배열을 같은 기준으로** 센다. 특히 「지금 할 일」로 위에 올라간
 * 한 장을 빼지 않는다 — 그 노드는 목록에서 사라지지 않고 **점선 한 줄**로 남아
 * 있으므로(ProcedureExecutionScreen 의 NodeSection), 빼면 접힌 줄의 수가 실제로
 * 보이는 줄 수보다 한 장 모자라게 된다.
 *
 * ──────────────────────────────────────────────────────────────────────
 * 접힌 줄에 덧말을 붙이는 까닭
 * ──────────────────────────────────────────────────────────────────────
 * 펼치지 않고도 알아야 할 것이 묶음마다 하나씩 있다.
 *
 *   - 전체 단계 보기 … 차단됨 수. 🔴 이 묶음은 **언제나 접혀 있으므로** 이
 *     딱지가 막힌 것을 알리는 **유일한 자리**다. 전에는 차단됨이 있으면 펼쳐
 *     두기도 했는데 그 규칙이 없어졌으니, 이 줄을 빼면 절차가 왜 안 흐르는지가
 *     화면 어디에도 안 적히게 된다.
 *   - 실행 이력 … 안에 든 **끝난 카드 수**를 완료와 건너뜀으로 **갈라서** 적는다.
 *     괄호 안 수는 이력 줄 수라서, 이것을 안 적으면 「지나온 길이 저 안에 있다」가
 *     접힌 줄에서 통째로 안 보인다. 건너뜀은 **안 한 일**이라 완료와 뜻이 다르다 —
 *     둘을 합쳐 「6」으로만 적으면 「여섯 개 했다」로 읽힌다.
 */

import type { ProcedureCaseExecutionNodeStatus } from "./procedure-case-execution-types";

export type FoldCandidate = { status: ProcedureCaseExecutionNodeStatus };

/**
 * 접지 않고 펼친 채로 두는 까닭. 접혀 있으면 null.
 *
 * 🔴 **지금 이 까닭을 다는 묶음이 하나도 없다**(2026-11-02, 조각 8). 「전체 단계
 * 보기」를 펼치던 까닭 둘(NO_CURRENT_TASK · HAS_BLOCKED)은 같은 날 사용자 결정으로
 * 없앴고, 마지막 하나였던 「지나온 길」의 ALL_FINISHED 는 그 묶음이 「실행 이력」
 * 안으로 들어가면서 함께 사라졌다 — 「실행 이력」은 **접힌 채가 기본**이다.
 *
 * 그래도 갈래와 그릇(open · openReason)은 **남긴다.** ExecutionFoldSection 이 그
 * 값으로 그리고 있고, 묶음 하나를 펼쳐 두기로 하는 날 정하는 자리가 여기여야
 * 한다 — 참·거짓 하나만 돌려주면 시험이 「펼쳐졌다」까지만 재고 **어느 까닭으로**
 * 펼쳐졌는지는 못 잰다(pickCurrentTask 와 같은 규약).
 *
 * 🔴 없앤 규칙 셋을 **되살리지 말 것.** 셋 다 눈으로 보고 내린 결정이다.
 */
export type ExecutionFoldOpenReason =
  /** 남은 것이 한 장도 없다. 지금은 아무 묶음도 이 까닭으로 펼치지 않는다. */
  "ALL_FINISHED";

export type ExecutionFoldNote = {
  text: string;
  /**
   * ATTENTION 은 「눈에 띄어야 하는 것」(차단됨), MUTED 는 「알아 두면 되는
   * 것」(완료·건너뜀). 색 이름을 여기 적지 않는 까닭은 이 파일이 화면을 모르기
   * 때문이다 — 무엇이 더 급한지만 정하고, 어떤 색인지는 컴포넌트가 정한다.
   */
  tone: "ATTENTION" | "MUTED";
};

export type ExecutionFoldGroup = {
  /** 접힌 줄에 그대로 뜨는 글자. 괄호 안 수까지 한 덩이다. */
  summary: string;
  /** 괄호 안 수 = 이 묶음이 담는 것의 수(제목이 가리키는 것으로 센다). */
  count: number;
  open: boolean;
  openReason: ExecutionFoldOpenReason | null;
  /** 제목 줄에 덧붙는 한 마디. 없으면 null — 그리는 쪽이 아무것도 안 그린다. */
  note: ExecutionFoldNote | null;
};

export type ExecutionListFold = {
  /**
   * 아직 안 끝난 것 — 대기 · 진행 중 · 차단됨.
   * 🔴 한 장도 없거나 **실행을 마쳤으면** null — 화면은 그 자리에 **아무것도 안
   * 그린다**(위 머리말).
   *
   * 🔵 짝이던 `done`(「지나온 길」)은 2026-11-02(조각 8)에 없어졌다 — 끝난 카드는
   * 「실행 이력」 묶음이 함께 담는다(buildExecutionHistoryFold). 칸만 남겨 두면
   * 쓰지도 않는 「지나온 길 (6)」이라는 글자가 값 안에 남아, 그것을 그리는 사람이
   * 나온다.
   */
  remaining: ExecutionFoldGroup | null;
};

function countOf(nodes: readonly FoldCandidate[], status: ProcedureCaseExecutionNodeStatus): number {
  return nodes.filter((n) => n.status === status).length;
}

/**
 * 「전체 단계 보기」 묶음의 머릿수 · 덧말 · **펼친 채로 둘지**를 정한다.
 *
 * `nodes` 에는 화면이 네 구역을 만들 때 쓰는 **그 배열을 그대로** 준다
 * (executionDetail.nodes). 걸러서 주면 괄호 안 수가 화면과 어긋난다.
 */
export function buildExecutionListFold(input: {
  nodes: readonly FoldCandidate[];
  /**
   * 🔴 실행을 마쳤는가(procedure_case_executions.completed_at 이 찼는가).
   * 마쳤으면 「전체 단계 보기」를 아예 안 그린다 — 까닭은 위 머리말.
   *
   * 「마쳤는가」를 여기서 다시 판정하지 않는다. 큰 카드·흐름 띠와 **같은 사실**을
   * 받아야 셋이 함께 물러난다.
   */
  isExecutionFinished: boolean;
}): ExecutionListFold {
  const blocked = countOf(input.nodes, "BLOCKED");
  const remainingCount = countOf(input.nodes, "PENDING") + countOf(input.nodes, "IN_PROGRESS") + blocked;

  return {
    // 🔴 `open` 이 상수 false 다. 「전체 단계 보기」는 어떤 경우에도 안 펼쳐진다
    // (2026-11-02 사용자 결정) — 차단됨이 있어도, 지금 할 일이 없어도.
    remaining:
      remainingCount === 0 || input.isExecutionFinished
        ? null
        : {
            summary: `전체 단계 보기 (${remainingCount})`,
            count: remainingCount,
            open: false,
            openReason: null,
            note: blocked > 0 ? { text: `차단됨 ${blocked}`, tone: "ATTENTION" } : null,
          },
  };
}

/**
 * 「실행 이력」 묶음 — **「지나온 길」을 품은** 한 덩이(2026-11-02, 조각 8).
 *
 * 안에 두 가지가 차례로 들어간다:
 *
 *   1. 끝난 노드 카드(완료 · 건너뜀) … 전에 「지나온 길」 묶음이 담던 그것.
 *      작업 메모 · 건너뛴 사유 · 차단 사유가 카드 안에 그대로 있다.
 *   2. 시각 기록 … 누가 언제 무엇을 했는가(ExecutionHistoryTimeline).
 *
 * ──────────────────────────────────────────────────────────────────────
 * 괄호 안 수를 **이력 줄 수**로 적는 까닭
 * ──────────────────────────────────────────────────────────────────────
 * 제목이 「실행 이력」이므로 괄호 안은 이력 줄 수다. 카드 수를 더해 한 수로
 * 뭉치면(「실행 이력 (18)」) 종류가 다른 둘을 더한 수가 되어, 이력 줄을 세어 본
 * 사람이 자기 눈과 다른 수를 보게 된다.
 *
 * 대신 **덧말로 카드 수를 적는다** — 「완료 5 · 건너뜀 1」. 이 묶음은 접힌 채로
 * 뜨므로, 이 글자가 없으면 「지나온 길이 저 안에 들어 있다」가 접힌 줄에서
 * 통째로 안 보인다. 완료와 건너뜀을 **갈라서** 적는 까닭은 위 머리말에 있다
 * (건너뜀은 안 한 일이다).
 *
 * 🔴 **접힌 채로** 뜬다(2026-11-02 사용자 결정, 조각 5). 「아까 뭘 했더라」를
 * 되짚을 때만 여는 것이라 평소에는 자리만 차지했다. 전에 「지나온 길」이 가지고
 * 있던 「남은 것이 0 장이면 펼친다」(ALL_FINISHED)는 여기로 따라오지 **않는다** —
 * 묶음마다 예외를 두면 접기가 다시 거의 안 듣는다.
 *
 * 🔵 아래 목록과 **같은 그릇**(ExecutionFoldSection)을 쓰려고 여기서 만든다 —
 * 화면마다 제 모양으로 접으면 「펼치기/접기」가 두 벌이 되고, 한쪽만 고치는 날이
 * 온다.
 *
 * 담을 것이 **둘 다 없으면** null — 이력 줄도 없고 끝낸 카드도 없는 실행이다.
 * 실제로는 실행을 시작한 줄(EXECUTION_STARTED)이 늘 있어서 그런 일은 거의 없지만,
 * 머릿수를 화면에서 다시 세지 않으려면 이 경우도 여기서 정해야 한다.
 */
export type ExecutionHistoryFold = {
  /** 접히는 묶음 한 덩이. 그릇은 「전체 단계 보기」와 똑같다. */
  fold: ExecutionFoldGroup;
  /**
   * 안에 **끝난 노드 카드 구역**을 그리는가. 끝낸 것이 한 장도 없으면 false —
   * 막 시작한 실행에서 「완료 / 건너뜀 (0)」과 「…없습니다」 한 줄이 접힌 묶음
   * 안에 덩그러니 남지 않게, 그 판정도 여기서 한다(화면이 doneNodes.length 를
   * 다시 세면 「빈 구역은 안 그린다」가 두 벌이 된다).
   */
  showsTrail: boolean;
};

export function buildExecutionHistoryFold(input: {
  /** 이력 줄 수(getExecutionHistory 가 돌려준 줄 수). */
  historyCount: number;
  /**
   * 화면이 네 구역을 만들 때 쓰는 **그 배열 그대로**(executionDetail.nodes).
   * 여기서 완료·건너뜀을 센다 — 걸러서 주면 덧말의 수가 화면과 어긋난다.
   */
  nodes: readonly FoldCandidate[];
}): ExecutionHistoryFold | null {
  const historyCount = Math.max(input.historyCount, 0);
  const completed = countOf(input.nodes, "COMPLETED");
  const skipped = countOf(input.nodes, "SKIPPED");
  const trailCount = completed + skipped;

  if (historyCount === 0 && trailCount === 0) return null;

  // 없는 것은 0 으로 적지 않고 아예 안 적는다 — 「건너뜀 0」은 읽을 가치가 없다.
  const noteParts: string[] = [];
  if (completed > 0) noteParts.push(`완료 ${completed}`);
  if (skipped > 0) noteParts.push(`건너뜀 ${skipped}`);

  return {
    fold: {
      summary: `실행 이력 (${historyCount})`,
      count: historyCount,
      open: false,
      openReason: null,
      note: noteParts.length > 0 ? { text: noteParts.join(" · "), tone: "MUTED" } : null,
    },
    showsTrail: trailCount > 0,
  };
}
