/**
 * 절차 하나를 사람에게 보일 때 쓰는 **한 줄 이름**. 순수 함수 하나뿐이다 —
 * DOM 도 React 도 DB 도 안 건드린다.
 *
 * ──────────────────────────────────────────────────────────────────────
 * 왜 함수가 필요한가 — 「이름 (이름)」이 실제로 떠 있었다
 * ──────────────────────────────────────────────────────────────────────
 * 화면 여러 곳이 `{name} ({code})` 로 적어 왔다. 코드는 들여올 때의 시트 번호나
 * 사람이 적은 짧은 글자라 보통 이름과 다르지만, **코드 칸에 이름이 그대로 들어간
 * 절차가 실제로 있다**(실측 2026-11-02: code 와 name 이 둘 다 「기본 통전 검사
 * (3상 입력)」). 그 절차를 실행하면 요약 카드에
 *
 *     기본 통전 검사 (3상 입력) (기본 통전 검사 (3상 입력))
 *
 * 이 떴다. 오류가 아니라 **글자만 이상한** 종류라 아무도 신고하지 않는다.
 *
 * ──────────────────────────────────────────────────────────────────────
 * 🔴 판정을 **한 곳에만** 둔다
 * ──────────────────────────────────────────────────────────────────────
 * 「코드를 붙일까 말까」를 화면마다 적으면 한쪽만 고치는 날이 온다. 둘 다 string
 * 이라 **컴파일러가 아무 말도 안 한다** — 이 저장소가 이미 겪은 종류의 어긋남이다
 * (같은 말이 두 벌로 정의돼 타입이 같아 침묵한 적이 있다). 그래서 쓰는 자리가
 * 셋이든 넷이든 이 함수 하나를 부른다.
 *
 * 🔵 **코드를 아예 안 보이게 하지는 않는다.** 이름이 같은 절차가 둘일 때 가를
 * 수단이 코드뿐이라, 다를 때는 그대로 괄호로 붙인다.
 */

/**
 * 「이름 (코드)」 — 다만 코드가 이름과 같거나 비었으면 **이름만**.
 *
 * 앞뒤 공백만 다른 것도 같은 것으로 본다. 들여온 자료에 공백이 섞여 들어오는
 * 일이 흔하고, 사람 눈에는 어차피 같은 글자다.
 */
export function formatProcedureTemplateTitle(templateName: string, templateCode: string | null | undefined): string {
  const code = (templateCode ?? "").trim();
  return code === "" || code === templateName.trim() ? templateName : `${templateName} (${code})`;
}
