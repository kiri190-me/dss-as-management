/**
 * ============================================================================
 * 견적서 부품 줄의 단가 — 어디서 온 줄인가가 정한다
 * ============================================================================
 * 부품 하나에 값이 둘 있다.
 *
 *   · `part_unit_prices`          — 부품 × 소유구분마다의 일반 단가
 *   · `part_overhaul_unit_prices` — 부품마다의 O/H 단가 (소유구분 없음)
 *
 * ── 🔴 견적서 종류가 아니라 **줄의 출처**가 고른다 ──────────────────────
 * (2026-08-31 사용자 결정. 그 전에는 "O/H 견적서면 O/H 단가"로 만들었다가 뒤집었다.)
 *
 *   · **출고된 부품에서 담은 줄** → 부품 상세에 적어 둔 **일반 단가**
 *   · **O/H 템플릿에서 불러온 줄** → 템플릿 쪽에 적어 둔 **O/H 단가**
 *
 * 한 O/H 견적서 안에 두 출처가 함께 있을 수 있어서 이 구분이 필요하다. 실제로
 * O/H 견적은 **부품을 출고하기 전에** 내므로 템플릿에서 오는 줄이 본체이고,
 * 출고 줄은 그 뒤에 실제로 쓴 것을 얹을 때 쓴다.
 *
 * 종류로 고르면 이 둘을 가를 수 없다 — 같은 견적서 안의 두 줄에 서로 다른 규칙이
 * 필요한데 종류는 견적서 하나에 하나뿐이기 때문이다.
 *
 * ── "정하지 않음"과 "0"은 다르다 ────────────────────────────────────────
 * null 은 "단가를 정하지 않았다"이고 `"0"` 은 "무상 부품"이라는 실제 값이다.
 * 정하지 않은 것을 0 으로 채우면 **견적서가 그 부품을 0원으로 청구한다.** 그래서
 * null 은 빈칸이 되고, `"0"` 은 `0` 으로 남는다
 * (schema/part-unit-prices.ts 머리말의 그 규칙).
 * ============================================================================
 */

/** 이 부품 줄이 어디서 왔는가. 어느 단가를 따르는지가 여기서 갈린다. */
export type QuotePriceOrigin =
  /** 이 접수 건에 실제로 출고된 부품에서 담았다 → 일반 단가. */
  | "ISSUED"
  /** 이 기종의 O/H 부품 템플릿에서 불러왔다 → O/H 단가. */
  | "OH_TEMPLATE";

/**
 * 단가를 화면의 입력 칸에 넣을 글자로 바꾼다.
 *
 * numeric 은 `"125000.00"` 으로 오는데 그대로 칸에 넣으면 사람이 적지도 않은
 * 소수점이 보인다. Number 를 한 번 거쳐 지운다 — 값 자체는 같다.
 *
 * **null 은 빈 문자열이다.** 0 으로 채우지 않는다(파일 머리말).
 */
export function toPriceFieldValue(price: string | null): string {
  if (price === null) return "";
  const parsed = Number(price);
  // 숫자로 안 읽히는 값을 String(Number(x)) 로 넘기면 "NaN" 이 칸에 박힌다.
  // 그럴 바에는 빈칸이 낫다 — 사람이 채우면 되고, NaN 은 저장에서 거절된다.
  return Number.isFinite(parsed) ? String(parsed) : "";
}

/** 단가를 정해 두지 않은 줄인가. 화면이 "단가 미정"이라 그릴지 정하는 데 쓴다. */
export function isPriceUnset(price: string | null): boolean {
  return price === null;
}
