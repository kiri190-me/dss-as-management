/**
 * ============================================================================
 * 견적서 [저장]이 **무슨 일을 했는가** — 결과 한 낱말 (2026-10-31)
 * ============================================================================
 * 저장은 이제 세 갈래로 끝난다. 갈래를 정하는 것은 **서버**이고, 화면은 그 낱말을
 * 보고 무엇을 띄울지만 고른다.
 *
 * 🔴 **화면이 스스로 가를 수 없다.** 수정 화면(QuoteEditForm)은 그 견적서의 결재가
 * 올라가 있는지조차 모른다 — 페이지가 결재 값을 [견적서 결재] 탭에만 내려보내기
 * 때문이다(quotes/[id]/page.tsx). 「바뀌었는가」도 마찬가지다: 폼은 자기가 들고
 * 있는 값만 알고 **DB 에 지금 무엇이 들어 있는지**는 모른다. 그래서 두 판단 다
 * 저장 경로가 내리고, 여기 적힌 낱말 하나로 건네준다.
 *
 * 🔴 **낱말을 글자로 적는 자리를 하나로 묶어 둔다.** mutation · 서버 액션 · 화면이
 * 각자 `"UNCHANGED"` 를 적으면 오타 하나가 「아무 팝업도 안 뜬다」로 조용히
 * 드러난다(오류가 나지 않는다 — 그냥 지금까지처럼 동작한다).
 *
 * ── 세 갈래 ────────────────────────────────────────────────────────────
 *  · `SAVED`                 지금까지 그대로다. 저장했고 결재는 건드리지 않았다.
 *                            (결재가 아예 없거나 이미 반려된 장이 여기다.)
 *  · `UNCHANGED`             🔴 **아무것도 바뀌지 않아 한 글자도 쓰지 않았다** —
 *                            판 번호도 그대로다. 결재도 그대로다.
 *  · `APPROVAL_AUTO_REJECTED` 저장했고, 올라가 있던 결재(대기 중·승인됨)를
 *                            **자동으로 반려**했다.
 *
 * 🔴 `UNCHANGED` 가 판 번호를 올리지 않는 것이 이 갈래의 존재 이유다. 올리면 그
 * 순간 승인 건이 「승인 후 변경됨」(APPROVED_OUTDATED)으로 읽혀, 반려하지 않기로
 * 한 결정이 아무 뜻도 없어진다(domain/quote-approval-rules.ts 의
 * resolveQuoteApprovalState).
 * ============================================================================
 */

export const QUOTE_SAVE_OUTCOMES = ["SAVED", "UNCHANGED", "APPROVAL_AUTO_REJECTED"] as const;
export type QuoteSaveOutcome = (typeof QUOTE_SAVE_OUTCOMES)[number];

/**
 * 사람이 **읽고 닫아야 하는** 알림이 필요한 결과인가.
 *
 * 🔴 `SAVED` 만 지금까지의 저장 팝업(0.5초 뒤 저절로 닫힌다)으로 끝난다. 나머지
 * 둘은 사람이 몰랐던 사실을 전하는 글이라 저절로 닫히는 팝업으로는 전할 수 없다
 * (common/NoticePopup.tsx 머리말 — 이 저장소에서 실제로 겪은 일이다).
 *
 * 타입 좁힘까지 겸한다: 참이면 부르는 쪽이 문구 표(Record)를 그대로 집을 수 있다.
 */
export function quoteSaveOutcomeNeedsNotice(
  outcome: QuoteSaveOutcome
): outcome is Exclude<QuoteSaveOutcome, "SAVED"> {
  return outcome !== "SAVED";
}
