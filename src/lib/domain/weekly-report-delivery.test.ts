import { test } from "node:test";
import assert from "node:assert/strict";
import { pickEarliestDueDate } from "./weekly-report-delivery";

/**
 * ============================================================================
 * 주간보고 납입 예정 건 — `입고 요청일`이 정말 '가장 이른 하루'인가
 * ============================================================================
 * 지키는 것은 넷이다.
 *
 *  1. **여럿이면 가장 이른 것 하나** — 준 차례와 상관없이 같은 답이 나온다.
 *  2. **여러 내자 줄에 걸친 날짜를 통틀어 본다** — 부르는 쪽이 묶어 넘기는
 *     것이라, 이 함수는 묶음이 몇 줄에서 왔는지 알지 못한다.
 *  3. **하나도 없으면 null** — 빈칸이다. 오류가 아니다.
 *  4. **지난 날짜도 그대로 고른다**(승인된 결정) — 오늘을 보지 않는다.
 *
 * 날짜 비교가 문자열로 이뤄지므로 **달·해 경계**를 함께 못 박는다. "9"와 "10"을
 * 숫자로 견주는 구현으로 바뀌면 그 자리에서 깨져야 한다.
 * ============================================================================
 */

test("여럿이면 가장 이른 하루를 고른다", () => {
  assert.equal(pickEarliestDueDate(["2026-09-30", "2026-08-31", "2026-12-01"]), "2026-08-31");
});

test("준 차례가 달라도 답은 같다", () => {
  const dates = ["2026-08-31", "2026-09-30", "2026-12-01"];
  assert.equal(pickEarliestDueDate(dates), pickEarliestDueDate([...dates].reverse()));
});

test("하나뿐이면 그것이다", () => {
  assert.equal(pickEarliestDueDate(["2026-08-31"]), "2026-08-31");
});

test("하나도 없으면 null — 빈칸이다", () => {
  assert.equal(pickEarliestDueDate([]), null);
});

test("같은 날짜가 여러 줄에 붙어 있어도 그 날짜다", () => {
  assert.equal(pickEarliestDueDate(["2026-08-31", "2026-08-31"]), "2026-08-31");
});

test("이미 지난 날짜라도 그것이 가장 이르면 그것을 적는다", () => {
  // 승인된 결정 — 오늘을 기준으로 걸러 내면 납기를 넘긴 건의 요청일이
  // 화면에서 사라져, 가장 급한 줄이 가장 늦어 보이는 표가 된다.
  assert.equal(pickEarliestDueDate(["2020-01-01", "2026-08-31"]), "2020-01-01");
});

test("달 경계 — 09월과 10월을 문자열로 견줘도 뒤집히지 않는다", () => {
  assert.equal(pickEarliestDueDate(["2026-10-01", "2026-09-30"]), "2026-09-30");
});

test("해 경계 — 12월 31일과 이듬해 1월 1일", () => {
  assert.equal(pickEarliestDueDate(["2027-01-01", "2026-12-31"]), "2026-12-31");
});

test("일(日) 경계 — 09일과 10일", () => {
  assert.equal(pickEarliestDueDate(["2026-08-10", "2026-08-09"]), "2026-08-09");
});
