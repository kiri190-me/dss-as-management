/** 판정에 쓰는 것만. 목록 줄(StoredQuoteKind)도 수정 자료(QuoteKind)도 그대로 들어온다. */
export type QuoteDocumentSubject = {
  kind: StoredQuoteKind;
  isExcelOnly: boolean;
};

/**
 * 앱 양식이 있는 종류 — **할 수 있는 쪽을 적는다.**
 *
 * 🔴 `kind !== "CABLE"` 로 쓰지 않은 것은 일부러다(domain/quote-list.ts 의
 * `=== "ITEM"` · schema 의 CHECK 들과 같은 방향이다). 그렇게 쓰면 종류가 하나 더
 * 생기는 날 그 종류가 **조용히 뚫려** 남의 양식으로 문서가 나간다. 할 수 있는 쪽을
 * 적어 두면 새 종류는 일단 막히고, 열려면 사람이 이 자리를 보게 된다.
 */
const APP_TEMPLATE_KINDS: readonly StoredQuoteKind[] = ["DOMESTIC", "OVERHAUL"];

export function canRenderQuoteDocument(quote: QuoteDocumentSubject): boolean {
  // 손으로 만든 엑셀 · 결재 PDF 가 그 장의 문서다 — 앱 양식을 쓰지 않는다(위 머리말).
  if (quote.isExcelOnly) return true;
  return APP_TEMPLATE_KINDS.includes(quote.kind);
}

