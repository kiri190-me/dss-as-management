import { purchaseOrderNumberKey } from "./purchase-order-folder-number";

/**
 * ============================================================================
 * 기타건(내자 정리 한 줄)의 **발주서 공유폴더를 무엇으로 찾는가** (순수 — 파일시스템 없음)
 * ============================================================================
 * 사용자 결정 2026-11-06: 「[발주서]는 내자정리에 적힌 **[발주서 번호]**를 통해서
 * 발주서들을 찾도록 해줘(수리건의 발주서 위치와 동일하고 … **같은 발주서 번호를 가진
 * 폴더와 연결**시켜줘)」.
 *
 * 이 파일이 하는 일은 **한 줄에서 찾을 열쇠 하나를 꺼내는 것**뿐이다. 🔴 **폴더를 찾는
 * 규칙은 여기 없다** — 폴더 이름에서 번호를 읽는 것도(domain/purchase-order-folder-number.ts),
 * 연도 · 고객사 켜를 훑는 것도(storage/purchase-order-number-archive.ts) 각자 한 벌이다.
 *
 * ── 🔴 **왜 수리 건의 길(L/N · S/N)이 아닌가** ───────────────────────────
 * 수리 건 「발주서」 탭은 폴더 이름의 **마지막 두 마디**(L/N · S/N)로 그 장비의 발주 건을
 * 찾는다. 🔴 기타건에는 **L/N 도 S/N 도 없다** — 부속 · 케이블 · 일식처럼 장비가 아닌 줄이
 * 대부분이라 그 길이 아예 안 통한다. 그래서 둘째 마디(번호)로 맞대는 길이 따로 있고,
 * 🔴 **수리 건 쪽 모듈은 이 조각에서 한 글자도 고치지 않았다**(느슨해지면 남의 발주서가
 * 뜨는 모듈이라 일부러 엄격하다).
 *
 * ── 🔴 **발주발행일로 문을 열지 않는다**(이쪽만 다르다 · 까닭이 있다) ──────
 * 수리 건 통로는 내자 정리의 **발주발행일이 비면 공유폴더를 아예 안 본다**(사용자 결정
 * 2026-10-12). 거기서 그 조건이 필요한 까닭은 **찾는 열쇠가 장비**이기 때문이다 — 발주가
 * 아직 안 나간 건에도 그 장비의 **지난 발주서**가 걸려 남의 발주서를 이 건의 것처럼 보여
 * 준다. 날짜가 그 사고를 막는 유일한 울타리였다.
 *  · 🔴 여기서는 **열쇠가 그 줄에 적힌 번호 자체**다. 번호가 적혀 있다는 것은 그 발주가
 *    이미 났다는 뜻이고, 그 번호의 폴더는 **정의상 이 줄의 발주 건**이다 — 지난 것도 남의
 *    것도 걸릴 수 없다. 날짜를 한 겹 더 걸면 **번호는 있는데 발주발행일 칸만 안 채운 줄**
 *    (내자 정리는 사람이 칸칸이 채우는 표다)에서 있는 폴더가 영영 안 보인다.
 *  · 🔴 그래서 이 줄 타입에는 `orderIssuedDate` 가 **아예 없다.** 안 쓰는 칸을 받아 두면
 *    다음 사람이 「왜 안 보지?」를 묻게 되고, 언젠가 조건으로 되살아난다.
 *
 * ── 🔴 번호를 화면에서 받지 않는다 ─────────────────────────────────────
 * 이 함수가 받는 것은 **내자 줄 그 자체**다. 통로(api/domestic-orders/[id]/
 * purchase-order-folder/entries)는 줄 id 만 받고 번호를 이 함수로 꺼낸다 — 번호를 요청에
 * 실어 보내게 만들면 내자 정리를 볼 수 있는 사람이 **아무 발주서 번호나 넣어 남의 발주 건
 * 폴더를 들여다볼 수 있다.** 그 폴더에는 다른 고객사의 발주서 · 금액이 그대로 있다.
 * ============================================================================
 */

/** 찾는 데 필요한 칸 하나. 🔴 날짜 칸이 없는 까닭은 머리말에 있다. */
export type DomesticOrderPurchaseOrderArchiveRow = {
  /**
   * 내자 정리에 **손으로 적은** 발주서번호(`purchase_order_number`). 🔴 이 칸에는 화면이
   * 고르는 짝(display*)이 없다 — 발주서는 시스템이 만드는 장이 아니라 고객사가 낸 서류라,
   * 그 번호가 적히는 곳이 이 칸 하나다.
   */
  purchaseOrderNumber: string | null;
};

export type DomesticOrderPurchaseOrderArchiveLookup =
  /** 찾아볼 수 있다 — 이 번호를 그대로 저장소 모듈에 넘긴다(앞뒤 공백만 턴 글자다). */
  | { status: "ready"; purchaseOrderNumber: string }
  /**
   * 🔴 쓸 수 있는 번호가 없다 — 찾을 열쇠가 없으므로 **공유폴더를 보지 않는다.**
   * 빈 칸뿐 아니라 `-` 한 글자처럼 **가리키는 것이 없는 값**도 여기로 온다(아래).
   */
  | { status: "no-po-number" };

/**
 * 이 줄의 발주서 공유폴더를 **무엇으로 찾을지** 정한다. 던지지 않는다.
 *
 * 🔴 「쓸 수 있는 번호인가」는 **폴더를 맞대는 그 함수**로 묻는다(purchaseOrderNumberKey).
 * 여기서 따로 「비었나」를 세면, 내자 정리에 실제로 들어 있는 `-` 한 글자가 번호 행세를 해
 * 화면에는 「공유폴더 — -」가 서고 저장소는 아무것도 못 찾는 어긋난 상태가 된다. 판정이
 * 한 벌이면 그런 줄은 **처음부터** 「번호가 없다」로 간다.
 *
 * 돌려주는 번호는 **열쇠가 아니라 사람이 적은 글자**다(앞뒤 공백만 턴 것) — 화면 머리에
 * 그대로 적히고, 맞대는 일은 저장소 쪽이 다시 열쇠로 바꿔서 한다.
 */
export function resolveDomesticOrderPurchaseOrderArchiveLookup(
  row: DomesticOrderPurchaseOrderArchiveRow
): DomesticOrderPurchaseOrderArchiveLookup {
  const written = typeof row?.purchaseOrderNumber === "string" ? row.purchaseOrderNumber.trim() : "";
  if (purchaseOrderNumberKey(written) === null) return { status: "no-po-number" };
  return { status: "ready", purchaseOrderNumber: written };
}

