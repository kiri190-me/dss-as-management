import { LABELS, type ShipmentApprovalState } from "./local/workflow/shipment-approval-checklist";

/**
 * ============================================================================
 * 🔴 **[최종 출하 승인 완료] 배지** — 글자 하나와 판정 하나 (2026-11-08)
 * ============================================================================
 * 사용자 요구 원문: 「**수리건과 기타건 모두 최종출하승인이 되면 [최종 출하 승인
 * 완료]라는 베찌**가 **현황판과 상세페이지 헤드, 내자정리의 [완료 처리]버튼의
 * 오른쪽**에 베찌가 붙도록 해줘」.
 *
 * 그 배지가 서는 자리가 **다섯**이다(전체 A/S 현황 · 수리 건 상세 머리 · 기타건
 * 현황 · 기타건 상세 머리 · 내자 정리의 완료 단추 옆). 🔴 다섯이 각자 「언제
 * 붙는가」를 적으면, 같은 건이 목록에서는 붙고 상세에서는 안 붙는 날이 온다 —
 * 이 저장소가 misc-case-status.ts 에서 이미 같은 까닭으로 판정을 한 곳에 모았다.
 *
 * ── 🔴 **판정을 새로 쓰지 않는다** ──────────────────────────────────────
 * 「승인이 났는가」는 접수 건 승인 카드 · 기타건 [승인] 탭 · 완료 관문이 전부
 * `resolveApprovalState` 하나로 답하고 있다(domain/local/workflow/
 * shipment-approval-checklist.ts). 이 파일이 하는 일은 그 다섯 상태 중
 * **어느 것에 배지를 붙일지**를 고르는 것 하나뿐이다.
 *
 * ── 🔴 `APPROVED` **하나만**이다 — `STALE` 은 안 붙는다 ──────────────────
 * 가장 헷갈리는 갈림이라 까닭을 적는다. `STALE` 은 「승인은 났는데 그 뒤 내용이
 * 바뀌었다」이고, 그 상태에서 [완료 처리]를 누르면 **서버가 거절한다**
 * (domain/domestic-order-approval-rules.ts 의 resolveMiscCaseCompletionGate 와
 * mutations/workflow-transitions.ts 의 APPROVAL_STALE 이 둘 다 막는다).
 *
 * 🔴 그러니 `STALE` 에 이 배지를 붙이면 **「승인 완료」라고 적힌 줄의 바로 옆
 * 단추가 「승인이 안 됐습니다」로 거절하는** 화면이 된다 — 이 저장소가 거듭
 * 겪고 적어 둔 「보이는 것과 되는 것이 다르다」 그 자리다(resolveApprovalState
 * 자체가 그 사고 때문에 생긴 함수다). 🔵 관문과 **같은 잣대**를 쓴다는 것이
 * 이 한 줄의 전부다.
 *
 * 🔵 `STALE` 인 줄이 아무 말도 못 듣는 것은 아니다 — 기타건은 상태 배지가
 * 「출하 재승인 필요」로 말하고(domain/misc-case-status.ts), 수리 건은 [승인]
 * 탭의 카드가 「재승인 필요」로 말한다. 이 배지는 **더할 말**이지 유일한 말이
 * 아니다.
 *
 * ── 🔵 회차를 접는 일은 여기서 하지 않는다 ──────────────────────────────
 * 기타건은 납기요청일 **회차마다** 승인이 선다(2026-11-08 사용자 결정 12). 여럿을
 * 하나로 접는 규칙은 이미 도메인 하나가 갖고 있고
 * (foldDomesticOrderApprovalStates), 이 함수는 **접힌 뒤의 상태 하나**를 받는다 —
 * 접는 일을 여기서 또 하면 완료 관문과 두 벌이 된다.
 * ============================================================================
 */

/**
 * 🔴 **사용자가 글자를 못 박았다** — 「[최종 출하 승인 완료]라는 베찌」.
 *
 * 그런데도 글자를 그대로 적지 않고 승인 이름표에서 만들어 쓴다. 까닭은 이
 * 저장소가 이름표를 다루는 규칙 그대로다(DOMESTIC_ORDER_APPROVAL_LABEL 의 그
 * 주석): 같은 절차가 [사용자 관리]의 고르개에서는 「최종 출하 승인」, 현황
 * 목록에서는 다른 말로 불리면 그것이 같은 것인지 알 수 없다.
 *
 * 🔵 그 대신 **지금 글자가 사용자가 말한 그대로인지**를 시험이 글자로 못 박는다
 * (lib/domain/final-shipment-approval-badge.test.ts) — 이름표가 바뀌는 날 조용히
 * 따라가지 않고 빨개진다.
 *
 * 🔴 **기타건도 같은 글자다.** 기타건 쪽 절차의 이름은 「기타건 최종 출하 승인」
 * 이지만(DOMESTIC_ORDER_APPROVAL_LABEL), 사용자가 두 화면에 **같은 배지**를
 * 요구했다(「수리건과 기타건 모두 … [최종 출하 승인 완료]라는 베찌」). 배지가
 * 답하는 물음이 「이 건의 최종 출하 승인이 끝났는가」 하나라, 거기에 종류 이름을
 * 섞으면 두 화면을 오가는 사람이 서로 다른 사실로 읽는다.
 */
export const FINAL_SHIPMENT_APPROVED_LABEL = `${LABELS.FINAL_SHIPMENT} 완료`;

/**
 * 그 건(또는 그 회차)에 **[최종 출하 승인 완료] 배지를 붙이는가.**
 *
 * `null`·`undefined` 는 「결재 기록이 한 줄도 없다」와 같은 뜻이다 — 목록 조회가
 * 기록 없는 줄을 지도에 아예 넣지 않으므로(queries 의 loadDomesticOrder…) 받는
 * 쪽이 `?? null` 로 메운 값이 그대로 들어온다.
 *
 * 🔴 **`STALE` 이 거짓인 것이 이 함수의 전부다**(파일 머리말).
 */
export function isFinalShipmentApproved(
  state: ShipmentApprovalState | null | undefined
): boolean {
  return state === "APPROVED";
}
