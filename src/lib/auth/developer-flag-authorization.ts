import type { AccountApprovalStatus } from "@/lib/domain/types";

/**
 * ============================================================================
 * 개발자 표시를 켜고 끌 수 있는 사람 — **진짜 최고관리자만**
 * ============================================================================
 * 뜻은 한 줄이다:
 *
 *     승인된 계정이고, 역할이 최고관리자다. 개발자 표시는 보지 않는다.
 *
 * ── 🔴 「최고관리자 동급」 규칙의 유일하고 의도된 예외 (2026-09-07 기획 결정) ──
 * users.is_developer 는 권한을 최고관리자급으로 올리는 스위치 **그 자체**다
 * (developer-promotion.ts). 이 자리에 `actorMay` 나 `hasPermission` 을 쓰면 개발자
 * 표시가 켜진 계정이 최고관리자로 판정되어 **개발자가 개발자를 만들 수 있다** —
 * 사람인 최고관리자가 개입하지 않고 승격이 번식하는 길이 생긴다. 그래서 이 판정
 * 하나만은 승격 창구를 지나지 않고 진짜 역할을 본다.
 *
 * 같은 이유로 `DEVELOPER_PROMOTED_ROLE` 도 부르지 않고 "SUPER_ADMIN" 을 그대로
 * 적는다 — 그 상수는 「개발자를 어느 역할로 승격하는가」이고, 여기서 묻는 것은
 * 「누가 그 승격을 켜고 끄는가」다(developer-mode-gate.ts 와 같은 판단).
 *
 * 최고관리자 역할은 통합 로그인 포털이 정하므로, 「최고관리자가 한 명도 없어서
 * 아무도 못 켜는」 잠김은 생길 수 없다 — 포털에서 새로 만들면 된다.
 *
 * ── 🔴 한 함수를 두 자리가 함께 쓴다 ────────────────────────────────────────
 *  - 화면: app/(app)/users/page.tsx 가 이 함수로 계산해 prop 으로 내려보낸다
 *    (단추의 활성 여부와 탭의 노출)
 *  - 서버: db/mutations/developer-flag.ts 가 트랜잭션 안에서 행위자를 다시 읽어
 *    **같은 함수**로 판정한다(실제 차단)
 *
 * 두 자리가 각자 식을 적으면 「단추는 보이는데 저장은 거절」이 된다 — 이 저장소가
 * 개발자 표시를 넣는 동안 두 번 겪은 어긋남이다. 식은 여기 한 번만 적는다.
 * 서버 액션(server/actions/developer-flag.ts)은 토큰의 역할로 미리 거르지 않는다 —
 * 토큰은 발급 시점 값이라, 살아 있는 행으로 판정하는 화면과 갈릴 수 있다.
 *
 * ── 승인 상태를 반드시 본다 ─────────────────────────────────────────────────
 * 승인은 승격 대상이 아니다(developer-flag.test.ts 의 같은 판단). 승인되지 않은
 * 최고관리자는 켤 수 없다.
 * ============================================================================
 */

/**
 * 판정이 보는 것 — 역할과 승인 상태. `ActingUser` 가 그대로 들어맞고, mutation 이
 * DB 에서 다시 읽은 행도 들어맞는다(구조적 타입). 개발자 표시는 **일부러 받지
 * 않는다** — 받는 모양에 있으면 언젠가 누가 그것을 보게 된다.
 */
export type DeveloperFlagManagerActor = {
  role: string;
  approvalStatus: AccountApprovalStatus;
};

/** 이 사람이 개발자 표시를 켜고 끌 수 있는가. 이 질문의 답은 여기 한 곳에서만 나온다. */
export function mayManageDeveloperFlag(actor: DeveloperFlagManagerActor): boolean {
  if (actor.approvalStatus !== "APPROVED") return false;
  return actor.role === "SUPER_ADMIN";
}
