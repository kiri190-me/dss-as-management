import type { Role } from "@/lib/domain/types";

/**
 * 주간보고(/dashboard/weekly-report) 화면의 서버 측 인가.
 *
 * domestic-order-authorization.ts 와 같은 관례다: Role 하나만 보는 순수 함수이고,
 * 화면이 무엇을 그릴지 정할 때 쓴다. 다만 **막는 곳은 여기가 아니다** — 페이지는
 * requireAreaAccessForCurrentUser("weeklyReport") 로 독립적으로 다시 검사하고,
 * 저장은 서버 액션이 이 판정에 더해 관리자가 설정한 수준(role_permissions)까지
 * 함께 본다. 화면에서 버튼을 감추는 것은 편의일 뿐이다.
 *
 * 정책(승인된 범위):
 *
 *  - **조회는 지금 그대로 전원이다.** 이 화면에 역할 함수가 생겼다고 해서 보는
 *    쪽이 좁아지지는 않는다 — 주간보고는 회사가 함께 보는 현황판이고, 금액이나
 *    입금 같은 영업 정보가 없어서 내자 정리처럼 역할을 가를 이유가 없다.
 *    그래서 canViewWeeklyReport 를 만들지 않는다: 아무도 막지 않는 함수는
 *    "이미 정해진 정책"처럼 읽혀서, 나중에 실제로 판단해야 할 것을 판단하지
 *    않고 지나가게 만든다(domestic-order-authorization.ts 의 '삭제·휴지통은
 *    아직 없다' 와 같은 이유다). 지금 달라지는 것은 **적을 수 있는가** 하나뿐이다.
 *
 *  - **금주 목표를 적을 수 있는 역할: 최고관리자 · 관리자 · A/S 엔지니어.**
 *
 *    금주 목표는 "이 장비를 이번 주에 어디까지 하겠다"는 **작업 계획**이다.
 *    그 계획을 세우고 지키는 사람이 A/S 엔지니어이고, 관리자는 그 위에서
 *    조정한다. 엔지니어가 볼 수만 있고 못 적으면 목표는 관리자가 대신 받아
 *    적는 값이 되고, 그러면 매주 옮겨 적는 사람이 하나 더 생긴 채 원본은
 *    여전히 엔지니어의 머릿속에 남는다 — 엑셀에서 벗어나려던 이유가 바로
 *    그것이다.
 *
 *    **영업 담당자(SALES)는 제외한다**(승인된 결정). 내자 정리에서 영업이 쓰기를
 *    갖는 이유는 그 표의 값(발주서번호·납품일·입금)을 실제로 아는 사람이
 *    영업이기 때문인데, 금주 목표는 그 반대다 — 이번 주에 어느 장비를 어디까지
 *    할지는 작업 쪽이 아는 값이다. 여기에 영업을 넣으면 같은 칸에 두 사람이
 *    서로 다른 근거로 적게 된다.
 *
 *    INVENTORY_MANAGER 가 빠지는 것은 내자 정리와 같은 이유다 — 부품 재고를
 *    다루는 자리이지 A/S 진행 계획을 세우는 자리가 아니다.
 *
 *  - **삭제도 같은 집합이다.** 줄 삭제는 휴지통 없이 바로 지우지만(승인된 결정),
 *    그렇다고 더 좁은 역할을 두지 않는다: 지워지는 것은 사람이 한 문장 적은
 *    메모이고, 잘못 지웠으면 그 주에 다시 적으면 된다. 되돌릴 수 없는 자료가
 *    사라지는 조작이 아니라서 '관리' 수준을 따로 만들지 않았고, 그래서 이
 *    함수 하나가 추가·수정·삭제·복사를 모두 답한다. 함수를 넷으로 나누면 같은
 *    목록이 네 벌이 되고, 그중 하나만 고쳐지는 날이 온다.
 */
export function canEditWeeklyReportGoals(role: Role): boolean {
  return role === "SUPER_ADMIN" || role === "ADMIN" || role === "AS_ENGINEER";
}
