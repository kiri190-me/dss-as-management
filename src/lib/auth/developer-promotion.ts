import type { Role } from "@/lib/domain/types";

/**
 * ============================================================================
 * 개발자 승격은 **더하기**다
 * ============================================================================
 *
 *     개발자의 권한 = 진짜 역할의 권한 ∪ 최고관리자의 권한
 *
 * 처음 구현은 역할을 갈아치우는 방식이었다(`isDeveloper ? "SUPER_ADMIN" : role`).
 * 그러면 **어떤 자리에서 최고관리자가 그 사람의 진짜 역할보다 낮으면 개발자가
 * 되는 것이 손해**가 된다. 실제로 그렇게 될 수 있는 자리가 둘 있고 둘 다 화면에서
 * 사람이 바꾸는 값이다:
 *
 *  1. `role_permissions` 표 — 최고관리자가 자기 역할의 어떤 영역을 A/S
 *     엔지니어보다 낮게 저장하면, 개발자 엔지니어가 그 영역에서 권한을 잃는다.
 *  2. 워크플로 전이의 `allowed_roles` — 초안 편집기에서 허용 역할을
 *     `["AS_ENGINEER"]` 만으로 만들 수 있다. 그러면 개발자 엔지니어는 진짜
 *     역할로는 통과하는데 승격 뒤에는 막힌다.
 *
 * 더하기로 두면 개발자가 자기 역할보다 못해지는 일이 **구조적으로 불가능**하다.
 * 모양이 셋이라 판정하는 자리마다 그중 하나를 고르면 된다:
 *
 *  - 수준(level)  → 둘 중 **높은** 쪽 (permission-resolver.ts)
 *  - 참/거짓      → 둘 중 하나라도 참이면 참 (`actorMay`)
 *  - 허용 역할 목록 → 진짜 역할이 있거나 최고관리자가 있으면 통과
 *                    (`actorHasAllowedRole`)
 *
 * ── 정책 함수는 손대지 않는다 ───────────────────────────────────────────────
 * `role === "SUPER_ADMIN"` 같은 비교가 들어 있는 `*-authorization.ts` 의 판정
 * 함수들은 한 글자도 바꾸지 않는다. 바뀌는 것은 **무엇을 넘겨 부르는가**다.
 * 정책 자체를 고치기 시작하면 60곳이 넘고, 하나만 틀려도 개발자가 아닌 다른
 * 역할의 권한이 달라진다.
 *
 * ── 승격이 인자인 이유 ──────────────────────────────────────────────────────
 * 여기서 세션이나 전역 상태를 몰래 읽지 않는다. 그러면 역할을 훑으며 같은 창구를
 * 부르는 자리(role-permission-views.ts 의 권한 설정 표)가 개발자에게만 전부
 * 「모든 권한」으로 보이고, 그 방향은 **열리는 쪽으로** 실패한다. 인자로 받으면
 * 호출부를 빠뜨려도 그 자리만 승격이 안 될 뿐이다.
 *
 * ── 승격하면 안 되는 것 ─────────────────────────────────────────────────────
 * 기준은 하나다: **「이 사람이 해도 되는가」는 승격하고, 「이것이 어떤 값인가」는
 * 승격하지 않는다.**
 *
 *  - 역할 이름표(`roleLabels`)·감사 기록의 행위자 — 값이다
 *  - 워크플로 초안 편집기의 「이 전이를 어느 역할에 허용할지」 체크박스
 *    (WorkflowDraftTransitionEditor.tsx) — 현재 사용자에 대한 판정이 아니라
 *    편집 중인 값이다. 여기서 승격하면 편집기가 엉뚱한 체크 상태를 보여 준다
 *  - 사람 ID 로 정해지는 것 — 출하 대리인·결재 위임·작업 배정. 역할 인자를
 *    받지 않으므로 손댈 자리가 애초에 없다
 *  - 권한 설정 화면의 표 — `roleOnlyActor()` 로 부른다(위 문단)
 *
 * ⚠️ 배정과 권한은 다른 축이다. `canReopenBlockedNode(role, assignment)` 처럼
 * 두 축을 함께 보는 함수는 **역할 축만** 더한다 — 개발자가 무조건 통과가 되는
 * 것은 「최고관리자 동급」이 맞고, 그 사람이 무엇에 배정됐는지는 달라지지 않는다.
 * ============================================================================
 */

/**
 * 승격의 다른 한쪽. 개발자는 최고관리자와 **동급 이상**이므로, 진짜 역할에
 * 이 역할의 권한을 더한다. 여러 파일이 같은 값을 쓰도록 여기 한 곳에 둔다.
 */
export const DEVELOPER_PROMOTED_ROLE: Role = "SUPER_ADMIN";

/**
 * 권한을 묻는 주체의 최소 모양. `ActingUser`·`PermissionActor` 가 그대로
 * 들어맞는다(구조적 타입).
 *
 * 역할 타입을 열어 둔 이유: 화면 컴포넌트 일부는 prop 을 `role: string` 으로
 * 받는다(서버에서 내려온 값을 그대로 표시만 하던 자리들). 그쪽까지 같은 창구를
 * 쓰게 하려고 `Role` 로 좁히지 않았다.
 */
export type PromotableActor<R extends string = Role> = {
  role: R;
  isDeveloper: boolean;
};

/**
 * 「이 사람이 해도 되는가」 — 진짜 역할로 되거나, 개발자면서 최고관리자로 되면
 * 된다. `decide` 는 기존 정책 함수를 **그대로** 넘긴다.
 *
 *     if (!canManageTechnicalTemplates(actor.role))        // 승격 없음
 *     if (!actorMay(actor, canManageTechnicalTemplates))   // 승격 있음
 *
 * 개발자가 아니면 `decide` 를 한 번만 부른다 — 답도, 부르는 횟수도 예전과 같다.
 */
export function actorMay<R extends string>(
  actor: PromotableActor<R>,
  decide: (role: R | Role) => boolean
): boolean {
  return decide(actor.role) || (actor.isDeveloper && decide(DEVELOPER_PROMOTED_ROLE));
}

/**
 * 허용 역할 목록으로 판정하는 자리 — 진짜 역할이 목록에 있거나, 개발자면서
 * 최고관리자가 목록에 있으면 통과한다.
 *
 * 목록이 최고관리자를 담고 있지 않으면 개발자도 통과하지 못한다. 그것이 맞다:
 * 「최고관리자 동급」이 「무엇이든 통과」는 아니다.
 */
export function actorHasAllowedRole(
  actor: PromotableActor<string>,
  allowed: readonly string[]
): boolean {
  return actorMay(actor, (role) => allowed.includes(role));
}
