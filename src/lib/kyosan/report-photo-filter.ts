import type { KyosanPhoto } from "./report-photos";

/**
 * ============================================================================
 * 연락서의 그림 가운데 **실제 사진만** 고른다 (2026-09-21, 조각 S3a)
 * ============================================================================
 * `report-photos.ts` 는 통합문서에 붙은 그림을 **전부** 모아 준다. 거기에는
 * 양식이 쓰는 아이콘 · 회사 도장 · 점검표 그림이 섞여 있다. 수리 건에 옮길 것은
 * 그 가운데 **사람이 찍은 사진**뿐이다.
 *
 * ── 🔴 규칙을 어떻게 정했는가 (469장 실측) ────────────────────────────
 * 기준이 필요했다. 실제 사진은 **그 연락서에만** 있고, 양식 자산은 **여러
 * 연락서에 똑같이** 들어 있다(같은 바이트다). 그래서 469장 전체에서 그림 내용
 * 해시를 세어, 「몇 개의 서로 다른 연락서에 나타나는가」를 정답으로 삼았다.
 * 결과는 깨끗하게 둘로 갈렸다 — 10KB 이상인 그림 13,750개 가운데:
 *
 *   · 1개 파일에만 있는 것        11,950개  ← 실제 사진
 *   · 2~4개 파일에 있는 것           956개  ← 같은 장비의 사진(연락서가 여러 장)
 *   · 5~19개 파일                      0개  ← 🔴 가운데가 비어 있다
 *   · 20개 파일 이상                 844개  ← 양식 자산(점검표 그림 · 양식 도안)
 *
 * 그 844개는 **단 다섯 종류**의 그림이 반복된 것이었다(78~246개 파일). 그래서
 * 규칙은 둘이다:
 *
 *   ▸ **10,240바이트(10KB) 이상**일 것
 *   ▸ 그리고 위 다섯 종류(`KYOSAN_FORM_ASSET_SHA256`)가 아닐 것
 *
 * 이 규칙의 실측 성적: 통과 12,906개 · 실제 사진을 놓친 것 52개(0.4%) ·
 * 양식 자산이 섞인 것 0개.
 *
 * ── 🔴 S1 이 제안한 「사진 시트 이름」 규칙은 쓰지 않는다 ─────────────
 * S1 보고는 `Photographs`·`参考写真`·`検査記録` 시트의 10KB 이상만 세자고 했다.
 * 실측해 보니 **실제 사진의 20%가 그 세 시트 밖에 있었다** — `通電検査`(728개) ·
 * `耐圧チェック`(582개) · `修理記録`(352개) · `マッチャーチェックシート`(220개) ·
 * `引取時のPARAMETER`(126개) 처럼 판본마다 다른 이름의 검사 시트들이다. 시트
 * 이름을 늘어놓는 규칙은 판본이 하나 늘 때마다 조용히 사진을 잃는다.
 * 크기 + 이미 드러난 양식 자산 목록이 더 튼튼하고, 무엇보다 **왜 그런지 셀 수
 * 있다**.
 *
 * ── 이 목록이 낡으면 어떻게 되는가 ────────────────────────────────────
 * 양식이 바뀌어 새 점검표 그림이 생기면 그것이 사진으로 섞여 들어온다(사진이
 * 몇 장 더 보이는 것뿐, **잃는 것은 없다**). 반대로 목록에 든 그림이 사라지면
 * 아무 일도 안 일어난다. 낡는 방향이 안전한 쪽이라 목록으로 둔다.
 * ============================================================================
 */

/** 이보다 작으면 사진으로 보지 않는다. 위 머리말의 실측. */
export const KYOSAN_PHOTO_MIN_BYTES = 10 * 1024;

/**
 * 🔴 469장 가운데 78~246장에 **똑같은 바이트로** 들어 있던 그림들. 한 장비의
 * 사진이 246건의 서로 다른 수리에 나타날 수는 없으므로 양식 자산이다.
 * 옆의 숫자는 (바이트, 나타난 연락서 수)이고 실측값 그대로다.
 * 🔴 해시는 그림 **내용**의 지문일 뿐 고객 정보가 아니다.
 */
export const KYOSAN_FORM_ASSET_SHA256: ReadonlySet<string> = new Set([
  // 125,425바이트 · 246장 — `必須確認事項`·`確認事項及び交換箇所` 의 점검표 그림
  "708efb75168c1cde50e0c2c1752da350584c982463758dc2432903532ea0276d",
  // 86,211바이트 · 245장 — 같은 두 시트의 둘째 점검표 그림
  "eb3967fd42cc9ffb62519aeca3a7017ac1bd4c29c0d43caa71cd82d927be2b1a",
  // 276,900바이트 · 152장 — `データ検査` 계열 시트의 양식 도안
  "9635814cb8982fe30b710fe3cbf018a75612bde34a1f35acc2416cb8a2d45931",
  // 22,148바이트 · 123장 — `Repair_Report`·`調査報告書GEx` 양식의 머리 그림
  "7994fbb4a15925c59a17d4c39e3517272e31254616cc434d7565a937666f970d",
  // 208,753바이트 · 78장 — `アンプリスト` 시트의 양식 도안
  "8727e47a7bd445c49407b1d0b893ed7e0ff667d37c16ca8a452f9ecb438e631c",
]);

/** 사람이 찍은 사진인가. 위 머리말의 두 규칙. */
export function isRealKyosanPhoto(photo: Pick<KyosanPhoto, "sha256" | "bytes">): boolean {
  if (photo.bytes < KYOSAN_PHOTO_MIN_BYTES) return false;
  return !KYOSAN_FORM_ASSET_SHA256.has(photo.sha256);
}

export type KyosanPhotoSplit = {
  /** 수리 건으로 옮길 사진들. */
  photos: readonly KyosanPhoto[];
  /** 걸러 낸 것들 — 양식 아이콘 · 도장 · 점검표 그림. 개수만 보여 주면 된다. */
  formAssets: readonly KyosanPhoto[];
};

/** 판독기가 모아 온 그림을 「사진」과 「양식 자산」으로 가른다. */
export function splitKyosanPhotos(photos: readonly KyosanPhoto[]): KyosanPhotoSplit {
  const real: KyosanPhoto[] = [];
  const formAssets: KyosanPhoto[] = [];
  for (const photo of photos) {
    if (isRealKyosanPhoto(photo)) real.push(photo);
    else formAssets.push(photo);
  }
  return { photos: real, formAssets };
}
