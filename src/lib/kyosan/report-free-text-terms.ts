const TERM_BY_KEY: ReadonlyMap<string, string> = new Map(
  Object.entries(KYOSAN_FREE_TEXT_TERMS).map(([japanese, korean]) => [
    kyosanCauseKey(japanese),
    korean,
  ])
);

/**
 * 자유 기술 사전에 있으면 한글을, 아니면 `null` 을 돌려준다.
 *
 * 🔴 **글자 통째로** 견준다 — 위 머리말의 '글자 통째로만 맞는다'.
 */
export function translateKyosanFreeTextTerm(value: string): string | null {
  return TERM_BY_KEY.get(kyosanCauseKey(value)) ?? null;
}

