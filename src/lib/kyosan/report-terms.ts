/** 눌린 열쇠로 찾는 표. 위 표에서 **만들어 낸다** — 두 벌로 적지 않는다. */
const TERM_BY_KEY: ReadonlyMap<string, string> = new Map(
  Object.entries(KYOSAN_FORM_TERMS).map(([japanese, korean]) => [kyosanCauseKey(japanese), korean])
);

/**
 * 가나 · 한자가 한 글자라도 있는가. 「이 줄은 일본어 원문이다」를 화면이
 * 알려 주는 데 쓴다.
 *
 * ⚠️ 한자 범위는 한국어 한자와 겹친다. 그래도 넣는 까닭은 연락서의 자유 기술이
 * `出力異常` 처럼 **가나 없이 한자만으로** 적히는 일이 흔하기 때문이다 — 빼면
 * 그 줄들이 「일본어 원문」 표시를 못 받는다. 우리 화면의 한국어는 한글로 적으므로
 * 잘못 걸릴 자리가 없다.
 */
const JAPANESE_CHARACTER = /[぀-ゟ゠-ヿ㐀-䶿一-鿿]/u;

export function hasJapaneseCharacter(value: string): boolean {
  return JAPANESE_CHARACTER.test(value);
}

/**
 * 양식의 고정 보기면 한글 이름을, 아니면 `null` 을 돌려준다.
 *
 * 🔴 **글자 통째로** 견준다 — 낱말을 잘라 바꾸지 않는다. 자유 기술 문장 속에
 * 우연히 `その他` 가 들어 있다고 그 조각만 한글이 되면, 위 머리말이 말한
 * 「반쪽 번역」이 바로 그것이다.
 */
export function translateKyosanFormTerm(value: string): string | null {
  return TERM_BY_KEY.get(kyosanCauseKey(value)) ?? null;
}

/**
 * 🔴 **사전 둘을 차례로 본다** — 양식의 고정 보기가 먼저, 그다음 자유 기술
 * (`report-free-text-terms.ts`).
 *
 * ── 왜 둘로 갈라 두고 여기서 합치는가 ───────────────────────────────
 * 위 열다섯은 **닫힌 목록**이고 우리 엑셀 양식의 칸 이름과 짝이 맞아야 한다
 * (`report-terms.test.ts` 가 개수와 짝을 못 박는다). 자유 기술은 **열린 목록**이고
 * 근거가 실측 빈도다. 한 표에 섞으면 그 단언이 무너지고 두 근거가 뒤섞인다.
 * 그래서 표는 둘, **찾는 문은 하나**다.
 *
 * 🔴 **차례가 뜻을 갖는다.** `交換無し` 는 양식 쪽에 있고, 자유 기술 쪽에는 같은
 * 글자를 넣지 않았다 — 나중에 실수로 두 쪽에 다 들어가도 **양식 쪽이 이긴다.**
 * 그쪽 값이 우리 엑셀 양식의 칸 이름이라, 문서의 다른 자리와 같은 낱말이 된다.
 *
 * `viewKyosanText` 가 이 함수를 쓴다 — 그래서 화면 셋과 문서가 **같은 사전**을
 * 본다. 층마다 다른 사전을 보면 화면에서 한글이던 줄이 문서에서 일본어로 나간다.
 */
export function translateKyosanTerm(value: string): string | null {
  return translateKyosanFormTerm(value) ?? translateKyosanFreeTextTerm(value);
}

export type KyosanTextView = {
  /** 🔴 연락서에서 온 글자 그대로. 언제나 채워진다 — 버리지 않는다. */
  original: string;
  /** 양식의 고정 보기일 때만 채워지는 한글 이름. 아니면 `null`. */
  korean: string | null;
  /**
   * 사전에 없는데 일본어가 든 글자인가. 화면이 「일본어 원문」이라고 알린다.
   * 고정 보기로 바뀐 줄은 `false` 다 — 이미 한글을 보여 주고 있기 때문이다.
   */
  isJapaneseOriginal: boolean;
};

/**
 * 화면 한 줄이 무엇을 보여 줘야 하는가. 순수 함수다.
 *
 *   · 고정 보기      → `korean` 을 크게, `original` 을 옆에 작게
 *   · 일본어 자유 기술 → `original` 그대로 + 「일본어 원문」 표시
 *   · 그 밖           → `original` 그대로
 */
export function viewKyosanText(value: string): KyosanTextView {
  // 🔴 사전 **둘 다** 본다 — `translateKyosanTerm` 의 '왜 둘로 갈라 두고' 참조.
  //
  // ⚠️ 2026-09-23 부터 한 걸음이 더 있다. `translateKyosanSentence` 가 **먼저**
  //    `translateKyosanTerm`(글자 통째로)을 보고, 거기서 못 찾은 줄만 **낱말
  //    바꿔치기**로 떨어뜨린다(`report-word-terms.ts`). 사전에 통째로 없는 긴
  //    줄이 문서에 일본어로 나가던 것을 막으려는 것이다.
  //    🔴 `translateKyosanTerm` 자체는 한 글자도 바뀌지 않았다 — 부르는 쪽인
  //    여기가 떨어질 자리를 하나 더 가진 것뿐이다. 낱말 바꿔치기는 **전부
  //    한글이 될 때만** 답을 주므로(all-or-nothing), 반쪽짜리가 `korean` 에
  //    들어오는 일은 없다.
  //    🔴 문서 쪽(`koreanKyosanDocumentText`)도 이 함수를 지나므로 **화면과 문서가
  //    여전히 같은 사전·같은 판정**을 본다(위 '층마다 다른 사전을 보면 안 된다').
  const korean = translateKyosanSentence(value);
  return {
    original: value,
    korean,
    isJapaneseOriginal: korean === null && hasJapaneseCharacter(value),
  };
}

/** 사전이 아는 보기 글자 전부. 시험이 열넷을 다 셌는지 못 박는 데 쓴다. */
export function knownKyosanFormTerms(): readonly string[] {
  return Object.keys(KYOSAN_FORM_TERMS);
}

// ─────────────────────────────────────────────── 여러 줄 덩어리 (2026-09-22)

/**
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 **덩어리를 통째로 태우면 아무것도 안 된다.**
 * ────────────────────────────────────────────────────────────────────────────
 * 이식은 연락서 여러 항목을 작업 기록 `memo` **한 덩어리**로 묶는다
 * (`report-detail-values.ts`). 실제로 저장된 모양은 이렇다:
 *
 *     [교산 연락서]          ← 사람이 적은 기록과 구별하는 표시
 *                            ← 빈 줄
 *     [사내 확인 결과]       ← 연락서의 항목 이름 머리글
 *     不具合内容 その１      ← 🔴 연락서 원문 그대로
 *
 * `viewKyosanText` 는 **글자 통째로** 견주므로 이 덩어리를 그대로 넘기면 언제나
 * `korean === null` 이다. **줄로 갈라 줄마다** 태워야 한다 — 그것이 이 함수다.
 *
 * ── 🔴 머리글 줄은 번역하지 않는다 ──────────────────────────────────
 * 대괄호 줄은 **우리가 붙인 한글 이름**이지 연락서 원문이 아니다
 * (`report-detail-values.ts:148` — 「대괄호는 연락서 원문에 나오지 않는 글자다」).
 * 사전에 걸릴 일도 「일본어 원문」으로 표시될 일도 없어야 한다.
 *
 * ── 🔴 앞뒤 공백을 지우지 않는다 ────────────────────────────────────
 * 저장 쪽이 연락서 칸의 공백을 **일부러 남긴다**(`"  前置きの空白も残す"`).
 * 여기서 `trim()` 을 부르면 그 결정을 화면이 뒤집는 것이 된다. 빈 줄도 그대로
 * 돌려준다 — 덩어리 사이 간격이 사라지면 어디까지가 한 항목인지 못 읽는다.
 * ────────────────────────────────────────────────────────────────────────────
 */
export type KyosanMemoLine =
  /** 대괄호 머리글 줄. 🔴 번역하지 않고 글자 그대로 보여 준다. */
  | { kind: "heading"; text: string }
  /** 빈 줄. 항목과 항목 사이의 간격이다. */
  | { kind: "blank" }
  /** 그 밖의 모든 줄. 한 줄이 무엇을 보여 줄지는 `view` 가 정한다. */
  | { kind: "text"; view: KyosanTextView };

/**
 * 머리글 줄의 모양. 저장 쪽(`report-detail-values.ts`)이 만드는 것은 둘뿐이다:
 *
 *     [사내 확인 결과]                 `kyosanOriginHeading(origin)`
 *     [교산 연락서] (2/3) 이어짐        4000자를 넘어 조각으로 나뉜 첫 줄
 *
 * ⚠️ 지시서는 「대괄호로 시작하고 **끝나는** 줄」이라고 적었지만 실제 코드는
 * 이어짐 표시를 대괄호 **뒤에** 붙인다 — `]` 로 끝나지 않는다. 실제 코드를 따른다.
 *
 * 🔴 일부러 좁게 잡았다. 작업 기록에는 사람이 손으로 적은 글도 들어오는데,
 * `[불량] 出力異常` 같은 줄까지 머리글로 보면 그 줄이 「일본어 원문」 표시를
 * 잃는다. 모양이 안 맞으면 그냥 보통 줄로 떨어질 뿐이라 잃는 것이 없다.
 */
const KYOSAN_HEADING_LINE = /^\[[^\][\r\n]*\](?:\s*\(\d+\/\d+\)(?:\s*이어짐)?)?$/u;

export function isKyosanHeadingLine(line: string): boolean {
  return KYOSAN_HEADING_LINE.test(line);
}

/**
 * 여러 줄 덩어리를 줄마다 「무엇을 보여 줄지」로 바꾼다. 순수 함수다.
 *
 * 줄 가름은 `\r\n` 도 받는다 — 줄을 나누는 글자일 뿐이라 내용이 달라지지 않는다.
 */
/**
 * 줄 하나가 무엇인가. 🔴 **가름의 규칙은 여기 한 곳뿐이다** — 아래
 * `viewKyosanMemoLines`(화면)와 `koreanKyosanDocumentText`(문서)가 이것을 함께
 * 쓴다. 두 벌로 적으면 「머리글은 번역하지 않는다」가 한쪽에서만 지켜지는 날이 온다.
 */
function classifyKyosanMemoLine(line: string): KyosanMemoLine {
  if (line === "") return { kind: "blank" };
  if (isKyosanHeadingLine(line)) return { kind: "heading", text: line };
  return { kind: "text", view: viewKyosanText(line) };
}

export function viewKyosanMemoLines(memo: string): readonly KyosanMemoLine[] {
  return memo.split(/\r?\n/).map(classifyKyosanMemoLine);
}

// ──────────────────────────────────────── 문서에 찍히는 글자 (2026-09-22)

/**
 * ────────────────────────────────────────────────────────────────────────────
 * 🔴 **문서는 한글만 찍는다 — 병기하지 않는다**(사용자 결정 2026-09-22)
 * ────────────────────────────────────────────────────────────────────────────
 * 화면(`components/kyosan/KyosanText.tsx`)은 한글 옆에 원문을 작게 함께 보인다.
 * 번역이 틀렸을 때 되짚을 자리가 화면에는 있어야 하기 때문이다. **문서는 다르다** —
 * 고객사로 나가는 종이에 `현품 인수(現品引取)` 라고 찍히면 그것은 두 나라 말이
 * 섞인 문서다. 그래서 문서 쪽은 `korean` 만 쓴다.
 *
 * 🔴 **사전에 없는 줄은 원문 그대로 나간다.** 사용자가 「사전에 없는 문장은
 * 일본어가 그대로 나와 한글과 섞여 보일 수 있습니다」라는 경고를 듣고 고른 것이다
 * (2026-09-22). 억지로 채우거나 빈 칸으로 만들지 않는다 — 빈 칸이 되면 연락서에
 * 적혀 있던 사실이 문서에서 사라진다.
 *
 * ── 🔴 줄바꿈 글자를 고치지 않는다 ──────────────────────────────────
 * 줄로 갈랐다가 `\n` 으로 다시 이으면 `\r\n` 이 조용히 `\n` 이 된다. 그것은
 * 번역이 아니라 **글자 바꾸기**다. 그래서 줄바꿈을 **갈라낸 채로 그대로 끼워**
 * 돌려준다(`split` 의 괄호가 그 일을 한다 — 짝수 칸이 줄, 홀수 칸이 줄바꿈).
 *
 * ── 🔴 앞뒤 공백도 그대로 ───────────────────────────────────────────
 * 양식의 글머리표가 앞 공백이고(`xlsx/service-report-template.ts` 의 '상황·본문·
 * 비고는 다듬지 않는다'), 저장 쪽도 연락서 칸의 공백을 일부러 남긴다. 사전이
 * 맞을 때만 그 줄이 한글로 바뀌고, 나머지 줄은 손대지 않는다.
 *
 * ⚠️ 사전이 맞아 한글이 된 줄은 **눌린 열쇠로** 맞은 것이라(NFKC + 공백 제거)
 * 앞뒤 공백이 함께 사라진다. 그 자리에 들어가는 것은 우리 양식의 한글 이름이고,
 * 그것은 공백이 붙지 않은 낱말이다.
 * ────────────────────────────────────────────────────────────────────────────
 */
export function koreanKyosanDocumentText(value: string): string {
  return value
    .split(/(\r?\n)/u)
    .map((piece, index) => {
      // 홀수 칸은 줄바꿈 글자 그대로다 — 위 '줄바꿈 글자를 고치지 않는다'.
      if (index % 2 === 1) return piece;
      const line = classifyKyosanMemoLine(piece);
      // 빈 줄과 머리글 줄은 손대지 않는다(머리글은 우리가 붙인 한글 이름이다).
      if (line.kind !== "text") return piece;
      return line.view.korean ?? piece;
    })
    .join("");
}
