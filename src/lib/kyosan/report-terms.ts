/** 눌린 열쇠로 찾는 표. 위 표에서 **만들어 낸다** — 두 벌로 적지 않는다. */
const TERM_BY_KEY: ReadonlyMap<string, string> = new Map(
  Object.entries(KYOSAN_FORM_TERMS).map(([japanese, korean]) => [kyosanCauseKey(japanese), korean])
);

/**
 * 가나 · 한자가 한 글자라도 있는가. 「이 줄은 일본어 원문이다」를 화면이
 * 알려 주는 데 쓴다.
 *
 * ⚠️ 한자 범위는 한국어 한자와 겹친다. 그래도 넣는 까닭은 연락서의 자유 기술이
 * `出力異常` 처럼 **가나 없이 한자만으로** 적히는 일이 흔하기 때문이다 — 빼면
 * 그 줄들이 「일본어 원문」 표시를 못 받는다. 우리 화면의 한국어는 한글로 적으므로
 * 잘못 걸릴 자리가 없다.
 */
const JAPANESE_CHARACTER = /[぀-ゟ゠-ヿ㐀-䶿一-鿿]/u;

export function hasJapaneseCharacter(value: string): boolean {
  return JAPANESE_CHARACTER.test(value);
}

/**
 * 양식의 고정 보기면 한글 이름을, 아니면 `null` 을 돌려준다.
 *
 * 🔴 **글자 통째로** 견준다 — 낱말을 잘라 바꾸지 않는다. 자유 기술 문장 속에
 * 우연히 `その他` 가 들어 있다고 그 조각만 한글이 되면, 위 머리말이 말한
 * 「반쪽 번역」이 바로 그것이다.
 */
export function translateKyosanFormTerm(value: string): string | null {
  return TERM_BY_KEY.get(kyosanCauseKey(value)) ?? null;
}

export type KyosanTextView = {
  /** 🔴 연락서에서 온 글자 그대로. 언제나 채워진다 — 버리지 않는다. */
  original: string;
  /** 양식의 고정 보기일 때만 채워지는 한글 이름. 아니면 `null`. */
  korean: string | null;
  /**
   * 사전에 없는데 일본어가 든 글자인가. 화면이 「일본어 원문」이라고 알린다.
   * 고정 보기로 바뀐 줄은 `false` 다 — 이미 한글을 보여 주고 있기 때문이다.
   */
  isJapaneseOriginal: boolean;
};

/**
 * 화면 한 줄이 무엇을 보여 줘야 하는가. 순수 함수다.
 *
 *   · 고정 보기      → `korean` 을 크게, `original` 을 옆에 작게
 *   · 일본어 자유 기술 → `original` 그대로 + 「일본어 원문」 표시
 *   · 그 밖           → `original` 그대로
 */
export function viewKyosanText(value: string): KyosanTextView {
  const korean = translateKyosanFormTerm(value);
  return {
    original: value,
    korean,
    isJapaneseOriginal: korean === null && hasJapaneseCharacter(value),
  };
}

/** 사전이 아는 보기 글자 전부. 시험이 열넷을 다 셌는지 못 박는 데 쓴다. */
export function knownKyosanFormTerms(): readonly string[] {
  return Object.keys(KYOSAN_FORM_TERMS);
}
