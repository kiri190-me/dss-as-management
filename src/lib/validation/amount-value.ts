/**
 * ============================================================================
 * 금액 한 칸의 규칙 — 형식만 본다
 * ============================================================================
 * 🔵 **원래 자리는 `part-unit-price-input.ts` 였다**(2026-10-27, 조각 13-C5 에서 옮겼다).
 *    옛 재고 기능이 걷히면서 그 파일(부품 단가 · O/H 단가)이 통째로 사라졌는데, 이 함수
 *    하나만은 **재고와 상관이 없는 쪽**이 쓰고 있었다 — `repair-task-input.ts` 의 수리
 *    작업비 **시간당 단가**다. 파일째 지우면 견적서의 작업비 칸이 함께 멈춘다.
 *    그래서 「금액 한 칸」만 남겨 여기로 옮겼다. 🔴 **본문은 한 글자도 바꾸지 않았다.**
 *
 * DB 도 세션도 여기서 만지지 않는다 — 순수 함수만 두어야 단위 시험이 그대로 붙는다.
 *
 * 🔴 **이름이 닮아 섞이기 쉬운 것**: `domain/amount-input.ts` 의 `parseAmountInput` 은
 *    **보여 주는 쪽**이다(세 자리 콤마를 붙이고 떼며 커서 자리를 셈한다). 이 파일은
 *    **받아들일 값인가**를 묻는다. 둘을 바꿔 쓰면 콤마가 붙은 채로 저장되거나,
 *    반대로 입력칸에서 글자가 사라진다.
 *
 * ── 🔴 빈 값은 0 이 아니다 ──────────────────────────────────────────────
 * 칸을 비운 것은 「금액을 정하지 않았다」는 뜻이고, 부르는 쪽은 그것을 `null` 로 받는다.
 * 0 으로 바꿔 버리면 「정하지 않음」을 다시 표현할 방법이 사라지고, **정하지 않은 값이
 * 0원으로 청구된다.** 0 은 그 자체로 「무상」이라는 뜻이다.
 *
 * ── 금액은 문자열로 오간다 ──────────────────────────────────────────────
 * 받는 칸이 numeric(15,2) 라 Number 를 거치지 않는다 — 0.1 을 더하는 것만으로도 오차가
 * 쌓이고, 그 오차가 견적서 합계와 세금계산서 사이의 1원 차이가 된다. 검증도 **문자열
 * 그대로 통과시켜** 저장까지 문자열로 간다.
 *
 * ── 받아들이는 값 ───────────────────────────────────────────────────────
 *   · 빈 문자열 · 공백만 · null · undefined  → null (정하지 않음)
 *   · "125000" · "1,250,000" · "1250.50" · 숫자 125000 → 정규화된 문자열
 *   · 음수 · 소수 세 자리 이상 · 정수부 14자리 이상 · 글자 · "1e3" → 거절
 * ============================================================================
 */

/**
 * numeric(15,2) — 정수부 13자리 + 소수부 2자리. 이 폭을 넘는 값을 그대로 넘기면
 * Postgres 가 22003(numeric field overflow)으로 거절하고, 그 오류는 사용자에게
 * 아무것도 설명하지 못한다. validation/quote-input.ts 와 같은 폭이다 — 이 값이
 * 그대로 견적서로 옮겨 가므로 폭이 다르면 옮기다 잘린다.
 */
const AMOUNT_PATTERN = /^\d{1,13}(?:\.\d{1,2})?$/;

/**
 * ── 🔴 금액 한 칸의 규칙은 여기 한 벌만 있다 ────────────────────────────
 * 쉼표 처리·자릿수·지수 표기 거절 같은 규칙이 여러 파일에 갈라져 있으면, 한쪽만
 * 고쳐지는 날 견적서 금액이 조용히 어긋난다 — 같은 견적서의 같은 칸으로 흘러가기
 * 때문에 어긋나도 눈에 띄지 않는다.
 *
 * 부품 id 같은 **줄을 가리키는 값은 여기서 보지 않는다.** 이 함수가 아는 것은
 * 금액 한 칸뿐이고, 그래서 성격이 다른 여러 금액 칸이 그대로 나눠 쓸 수 있다.
 *
 * 받아들이는 값은 이 파일 머리말의 「받아들이는 값」과 같다. 쉼표를 지우는 것은
 * 사람이 금액을 그렇게 치기 때문이고, 지수 표기를 막는 것은 Number() 에 맡기면
 * "1e3" 이 1000 으로 조용히 통과하기 때문이다.
 *
 * 🔴 **거절 문구에 「단가」라고 적혀 있다.** 옮기기 전 그대로다 — 지금 부르는 쪽이
 *    시간당 **단가** 하나뿐이라 사람이 읽는 말이 어긋나지 않는다. 성격이 다른 금액
 *    칸이 붙는 날에는 부르는 쪽에서 제 말로 바꿔 보여 줄 것.
 */
export function parseAmountValue(
  raw: unknown
): { ok: true; value: string | null } | { ok: false; message: string } {
  if (raw === null || raw === undefined) return { ok: true, value: null };

  const text = typeof raw === "number" ? (Number.isFinite(raw) ? String(raw) : "") : raw;
  if (typeof text !== "string") return { ok: false, message: "단가 값을 확인할 수 없습니다." };

  // 사람이 금액을 "1,250,000" 으로 친다. 쉼표만 지우고 나머지는 그대로 본다.
  const trimmed = text.trim().replace(/,/g, "");
  // 비운 칸 — 정하지 않음.
  if (trimmed === "") return { ok: true, value: null };

  if (!AMOUNT_PATTERN.test(trimmed)) {
    return { ok: false, message: "단가는 0 이상의 금액(소수점 두 자리까지)이어야 합니다." };
  }
  return { ok: true, value: trimmed };
}
