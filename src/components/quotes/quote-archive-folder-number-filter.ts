import { quoteArchiveNumberKey, quoteNumberFromArchiveFileName } from "@/lib/domain/quote-archive-file-number";

/**
 * ============================================================================
 * 폴더 안의 줄에서 **보고 있는 견적서 번호의 파일만** 남긴다 (순수 — 파일시스템 없음)
 * ============================================================================
 * 공유폴더의 폴더를 가르는 것은 **본 번호**다(domain/quote-archive-naming.ts 의
 * quoteArchiveBaseNumber — 가지 번호 한 겹만 뗀다). 그래서 `DSS 2026-089` 와
 * `DSS 2026-089-1` 은 **같은 폴더**를 쓰고, 가지 번호 견적서를 열어도 본 번호의 파일까지
 * 목록에 뜬다:
 *
 *   21. 2026 내자견적서/
 *     DSS 2026-089 가나상사 MODEL-X1 L123 S456 전원 불량/      ← 폴더는 본 번호 하나
 *       DSS 2026-089 … .xls                                   ← 본 번호의 것
 *       DSS 2026-089 … - 有印.pdf                             ← 본 번호의 결재본
 *       DSS 2026-089-1 … (OH포함).xls                         ← **다른 장**의 것
 *
 * 결재 탭(`/quotes/[id]`)은 **그 한 장**을 결재하는 자리라 그 장의 파일만 보여야 한다
 * (사용자 요구 2026-10-12). 이 모듈이 그 거르기 하나만 한다.
 *
 * ── 🔴 견주기를 **새로 만들지 않았다** — [Excel 보기]와 같은 한 벌이다 ────
 * 번호를 뽑는 함수 한 벌(domain/quote-archive-file-number.ts)에 **양쪽을 태워** 키를
 * 견준다:
 *   · 견적서 쪽 — 발행번호 `DSS 2026-078-3` → `2026-078-3` (quoteArchiveNumberKey)
 *   · 파일 쪽   — `DSS 2026-078-3 가나상사 ….xlsx` → `2026-078-3`
 * 🔴 **이것이 [Excel 보기]가 쓰는 그 규칙이다**(quote-archive-excel-open.ts 의
 * pickQuoteArchiveExcelEntry). 다른 규칙으로 거르면 **같은 화면 안에서 둘이 싸운다** —
 * [Excel 보기]는 찾아 여는 파일을 바로 옆 공유폴더 구역이 숨기는 식으로. 한때 그렇게
 * 만들었다가(2026-10-12 첫 판은 matchesShareFolderPrefix 로 글자 앞머리를 봤다) 실측 이름
 * 때문에 바로잡았다.
 *
 * 그 규칙이 접어 주는 것(2026-10-06 실측, 2026 연도 폴더 파일 342 개):
 *   · `DSS-2026-099 …` — 번호가 자유 입력이라 **하이픈**으로 적힌 것
 *   · `dss 2026-001 …` · `2026-004r1` — **소문자**로 적힌 것
 *   · `DSS  2026-007  …` — 두 칸 띄어쓰기 · NFD 한글 · 앞뒤 공백
 * 그 규칙이 **일부러 안 받는** 것:
 *   · `DSS 2026-046- ICD …` — 번호 뒤가 공백이 아닌 오타(실측 3 개). 사람이 적지 않은
 *     번호를 지어내지 않으려고 `null` 이다 → 여기서는 **숨는다**(개수에 센다).
 *   · 이름이 번호에서 끝나는 것(`DSS 2026-089.xlsx`) — 같은 까닭으로 번호가 안 뽑힌다.
 *
 * ── 🔴 **본 번호로 깎지 않는다** ─────────────────────────────────────────
 * `quoteArchiveBaseNumber` 를 태우면 `DSS 2026-089-1` 이 `DSS 2026-089` 가 되어 지금과
 * 똑같이 전부 보인다. 여기서 견주는 것은 **견적서 번호 전체**이고, 가지(`-1`)와
 * 개정(`R1`) 한 겹이 키에 그대로 남는다 — `DSS 2026-004R1` 의 파일은 `DSS 2026-004`
 * 견적서에서 숨는다.
 *
 * ── 🔴 **키를 못 뽑으면 거르지 않는다** ──────────────────────────────────
 * 발행번호가 비었거나 사내 모양이 아니면(`Q-7` · `DSS2026-089` 처럼 개발 DB 에 있는 것들)
 * 키가 `null` 이다. 그때 「맞는 것이 없다」로 보면 **파일이 통째로 사라진다.** 그래서
 * **전부 보인다** — 번호를 주지 않은 화면(수리 건 「견적서」 탭)이 지나는 길과 같다.
 * (옆 모듈 pickQuoteArchiveExcelEntry 는 같은 자리에서 **아무것도 고르지 않는다.** 거기는
 * 「열 파일 하나」를 고르는 일이라 지어내지 않는 쪽이 안전하고, 여기는 「숨길까」라 보이는
 * 쪽이 안전하다 — 방향이 반대인 것이 맞다.)
 *
 * ── 🔴 숨긴 개수를 함께 돌려준다 ─────────────────────────────────────────
 * 사람이 손으로 넣은 파일(`참고자료.pdf` 처럼 번호로 시작하지 않는 것)도 숨겨진다. 안내가
 * 없으면 쓰는 분이 「파일이 없어졌다」고 여기므로, 화면이 그 개수를 한 줄로 알릴 수 있게
 * 세어서 함께 준다.
 *
 * ── 🔴 **화면에서만 거른다** ─────────────────────────────────────────────
 * 서버 통로(`/api/quotes/[id]/archive-folder/entries`)는 한 줄도 건드리지 않는다 — 그 통로는
 * 다른 화면([Excel 보기] · 수리 건 「견적서」 탭)도 쓴다. 이미 받아 둔 줄을 보이는 몫에서만
 * 덜어낼 뿐이다.
 * ============================================================================
 */

/** 거른 결과 — 남은 줄과 **숨긴 개수**. */
export type QuoteArchiveFolderNumberFilterResult<T> = {
  /** 보일 줄. 차례는 받은 그대로다 — 서버가 준 차례를 흔들지 않는다. */
  entries: readonly T[];
  /** 이 번호의 것이 아니어서 덜어낸 줄 수. 거르지 않았으면 0 이다. */
  hiddenCount: number;
};

/**
 * 폴더 안의 줄에서 **이 견적서 번호의 것만** 남긴다. 던지지 않는다.
 *
 *  · 발행번호에서 키를 못 뽑으면 **받은 배열을 그대로** 돌려준다(새 배열을 만들지 않는다).
 *  · 파일 이름에서 키를 못 뽑는 줄은 맞지 않는 것으로 본다 — 숨긴 개수에 센다.
 */
export function filterQuoteArchiveEntriesByQuoteNumber<T extends { name: string }>(
  entries: readonly T[],
  quoteNumber: string
): QuoteArchiveFolderNumberFilterResult<T> {
  const wanted = quoteArchiveNumberKey(quoteNumber);
  // 🔴 번호를 모르면 거르지 않는다 — 「맞는 것이 없다」로 보면 파일이 통째로 사라진다.
  if (wanted === null) return { entries, hiddenCount: 0 };

  const kept = entries.filter((entry) => entry != null && quoteNumberFromArchiveFileName(entry.name) === wanted);
  return { entries: kept, hiddenCount: entries.length - kept.length };
}
