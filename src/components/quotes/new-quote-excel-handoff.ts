/**
 * ============================================================================
 * 「새 견적서」 팝업 → 작성 화면. 파일 하나를 건네는 인계 상자 (견적서 ⑤b)
 * ============================================================================
 * 팝업의 [만들기]는 `<Link>` 로 `/quotes/new?kind=…&excelOnly=1` 로 **이동**한다. 주소에는
 * 고른 값만 실리고 **파일은 실을 수 없다**. 그 이동은 브라우저 새로고침이 아니라 앱 안에서의
 * 이동이라 자바스크립트 메모리가 살아남는다 — 그래서 모듈 수준의 작은 상자 하나에 담아
 * 건넨다. 담는 곳은 팝업의 [만들기] 한 곳, 꺼내는 곳은 작성 폼의 첫 그림 한 곳이다.
 *
 * ── 🔴 비어도 망가지지 않는다 ────────────────────────────────────────────
 * 새로고침 · 주소 직접 입력 · 뒤로가기 · 북마크로 들어오면 상자는 비어 있다. 그때 폼은
 * **지금까지와 똑같이** 열린다 — 사람이 「수기 견적서 엑셀」 칸에 직접 붙이면 된다. 상자가
 * 비었다는 것은 오류가 아니라 보통 상태다.
 *
 * ── 🔴 한 번 꺼내면 비운다 ───────────────────────────────────────────────
 * `take` 는 꺼내면서 상자를 비운다. 안 그러면 나중에 그 주소를 다시 열었을 때(뒤로가기로
 * 돌아왔을 때 등) 엉뚱한 파일이 말없이 붙는다. 그리고 [만들기]는 담을 것이 없을 때도
 * **상자를 비우며**(`put(null)`) 간다 — 앞서 고르다 만 파일이 남아 따라오지 않게.
 *
 * ── 왜 값을 여기에 두는가 ────────────────────────────────────────────────
 * 나르는 것은 **파일과 고른 시트 차례 둘뿐**이다. 읽은 값(공급처 · 금액 …)을 담아 나르지
 * 않는다 — 폼을 채우는 길은 「엑셀 칸에 파일을 고른다」 하나여야 하고(quote-excel-autofill.ts),
 * 상자가 두 번째 길이 되면 두 입구가 서로 다른 값을 채우는 날이 온다.
 * ============================================================================
 */

export type NewQuoteExcelHandoff = {
  /** 팝업에서 고른 수기 견적서 엑셀. 폼의 「수기 견적서 엑셀」 칸이 그대로 받는다. */
  file: File;
  /**
   * 고른 견적서 종류에 짝지어지는 탭 차례(읽기 통로의 `?sheet=`). 짝이 없으면 null —
   * 그때는 시트를 지정하지 않고 통로가 혼자 고른다(new-quote-excel-sheets.ts).
   */
  sheetIndex: number | null;
};

/** 건너가는 중인 것 하나. 팝업은 한 번에 하나만 열리므로 자리도 하나다. */
let handoff: NewQuoteExcelHandoff | null = null;

/**
 * 담는다. `null` 을 주면 **비운다** — [만들기]가 파일 없이 갈 때도 이것을 불러, 앞서 남은
 * 것이 따라가지 않게 한다.
 */
export function putNewQuoteExcelHandoff(next: NewQuoteExcelHandoff | null): void {
  handoff = next;
}

/** 꺼내고 **비운다**. 비어 있으면 null 이다 — 부르는 쪽은 그때 아무 일도 하지 않는다. */
export function takeNewQuoteExcelHandoff(): NewQuoteExcelHandoff | null {
  const taken = handoff;
  handoff = null;
  return taken;
}
