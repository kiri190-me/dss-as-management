/**
 * ============================================================================
 * 날짜 칸의 연도를 네 자리로 묶는 값 둘 (2026-11-05)
 * ============================================================================
 * 사용자 요구다 — 「연도에 여섯 글자가 들어간다. 네 글자만 들어가게 하고, 네
 * 글자를 치면 월로 넘어가게 해 달라」.
 *
 * 🔵 **크롬의 `<input type="date">` 는 상한이 없으면 연도 칸을 여섯 자리로 연다.**
 * 내부 상한이 275760년이라 그 자릿수를 다 받아 주는 것이다. 그래서 `202611` 을
 * 치면 연도가 `202611` 로 차고 월로 넘어가지도 않는다 — 2026-11-05 에 A/S 접수
 * 화면에서 그대로 재현했다(`202611-월-일`). 같은 칸에 `max="9999-12-31"` 을 준
 * 뒤에는 `2026-11-일` 이 됐다: 연도 네 글자에서 월로 저절로 넘어가고, 이어 친
 * `11` 이 월에 들어간다. 자릿수를 정하는 것이 `max` 의 자릿수라서다.
 *
 * 🔵 **월 → 일 은 손댈 것이 없다.** 월에 두 글자를 치면 브라우저가 이미 일로
 * 넘긴다(같은 날 실측). 그래서 이 저장소에는 날짜 칸의 키를 가로채는 코드가 없고
 * 들여서도 안 된다 — 날짜 칸의 키 조작은 브라우저가 OS 의 지역 설정까지 보고
 * 하는 일이라, 손으로 흉내 내면 흉내 낸 만큼 자리마다 다르게 깨진다.
 *
 * 🔴 **업무 상한이 아니다.** `9999-12-31` 은 「연도는 네 자리」라는 말을 HTML 로
 * 옮겨 적은 것뿐이고, 실제로 막고 싶은 날짜가 있어서 고른 값이 아니다. 이 값을
 * `2030-12-31` 처럼 좁히면 먼 미래 납기일을 적어야 하는 칸들이 소리 없이 거절당한다
 * — 그런 제한이 필요한 칸이 생기면 그 칸 하나에 따로 적을 일이지 여기를 건드릴
 * 일이 아니다.
 *
 * 🔴 **짝이 되는 `min` 은 일부러 두지 않았다.** 하한을 걸면 과거 건을 적는 자리
 * (옛 인수일 · 옛 발주발행일)가 막힌다. 자릿수를 묶는 데는 `max` 하나로 충분하다.
 *
 * 🔴 이 파일에 React 가 없는 것은 일부러다 — 이웃인 repair-cases/due-date-near.ts
 * 머리말과 같은 까닭이다. "use client" 가 붙은 조각에 상수를 두면 서버 컴포넌트가
 * 그 값을 읽을 때 클라이언트 참조가 된다. 글자 한 벌만 드는 이 파일은 서버에서도
 * 화면에서도 그냥 문자열이다.
 *
 * 🔴 **새 날짜 칸이 이 값을 빠뜨려도 아무 오류가 나지 않는다** — 그 칸만 조용히
 * 여섯 자리를 받고, 신고가 들어오기 전에는 아무도 모른다. 그래서 소스를 훑어 빠진
 * 칸을 찾는 시험을 따로 둔다: date-input-max-screens.test.ts.
 *
 * 🔵 `<input type="datetime-local">` 도 **같은 결함이다 — 그날 재서 확인했다.**
 * 결재권 위임 화면(/users 의 「결재권 위임」 탭)의 「시작 일시」 칸에서 연도에
 * `202611` 을 쳤더니 `202611-11-05 오전 10:21` 이 됐다. 날짜 칸과 똑같이 연도가
 * 여섯 자리를 그대로 받는다. 그래서 아래 DATETIME_LOCAL_INPUT_MAX 가 함께 있다.
 * (이 절은 처음 적을 때 「재 보지 않았다」였다. 2026-11-05 에 실측으로 갱신했다 —
 * 안 고치면 다음 사람이 「아직 아무도 안 재 봤구나」로 읽는다.)
 * ============================================================================
 */
export const DATE_INPUT_MAX = "9999-12-31";

/**
 * `<input type="datetime-local">` 의 상한. 위 값과 **같은 날**이고 그날의 끝 시각이다.
 *
 * 🔴 **`DATE_INPUT_MAX` 를 그대로 주면 안 된다.** `datetime-local` 의 `max` 는
 * 시각까지 있어야 브라우저가 값으로 받아 준다 — `9999-12-31` 만 주면 그 칸의
 * 상한은 **통째로 무시되고** 연도가 도로 여섯 자리가 된다. 거꾸로 날짜 칸에 이
 * 값(`…T23:59`)을 주어도 마찬가지다.
 *
 * 🔴 **둘이 뒤바뀌어도 아무 오류가 안 난다.** 콘솔에 경고 한 줄 없이 고치기 전으로
 * 돌아갈 뿐이라, 고친 사람도 고쳐진 줄 안다. 그래서 date-input-max-screens.test.ts
 * 가 「어느 칸이 어느 상수를 드는가」를 칸마다 따로 못 박는다.
 *
 * 🔵 `T` 앞은 DATE_INPUT_MAX 와 글자까지 같다. 한쪽만 고치면 두 칸의 상한이 다른
 * 날이 되므로, 바꿀 일이 생기면 **둘을 같이** 바꾼다(그 짝도 시험이 본다).
 */
export const DATETIME_LOCAL_INPUT_MAX = "9999-12-31T23:59";
