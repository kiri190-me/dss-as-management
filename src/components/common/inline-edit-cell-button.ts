/**
 * ============================================================================
 * 칸을 눌러 그 자리에서 고치는 글자의 겉모습 — 여러 표가 **나눠 쓰는** 값
 * ============================================================================
 * 이 저장소에는 `수정` 버튼 없이 **칸을 누르면 곧바로 편집으로 들어가는** 칸이
 * 여럿 있다:
 *   - 주간보고 고객사 상세표의 `비고`(WeeklyReportNotesCell)
 *   - 주간보고 맨 아래 납입 예정 건 표의 `비고`(WeeklyReportDeliveriesPanel 의
 *     DeliveryLine)
 *   - 내자 정리 표·카드의 한 줄짜리 글자 칸 다섯(DomesticOrderTextCell)
 *
 * 주간보고 두 칸이 그렇게 정해진 이유는 "한 화면에 비고가 둘인데 하나만 눌러서
 * 열리면 오히려 더 헷갈린다"였다(사용자 결정). 내자 정리가 셋째로 합류하면서
 * 이 값은 한 화면의 문제가 아니라 **이 서비스에서 '칸을 눌러 고친다'가 어떻게
 * 생겼는가**가 되었다.
 *
 * ── 왜 값을 이 파일 한 곳에 두는가 ──────────────────────────────────────
 * `수정` 이라는 글자가 사라졌으므로, **단서가 없으면 여기를 고칠 수 있다는 사실을
 * 아무도 모른다.** 그 자리를 메우는 것이 아래 두 값이다 — hover 배경과 손가락
 * 커서(마우스), focus-visible 테두리(키보드로 훑는 사람에게는 이것이 유일한
 * 단서다), 그리고 올려 두면 뜨는 title. 까닭은 WeeklyReportNotesCell 헤더에
 * 자세히 적혀 있다.
 *
 * 이 문자열을 파일마다 각각 적으면 **언젠가 한쪽만 고쳐진다.** 그 순간 눌러서
 * 고치는 칸들이 서로 다르게 보이고, 그러면 애초에 버튼을 없앤 뜻이 사라진다 —
 * "이 값은 눌러서 고친다"가 한 가지 규칙으로 읽혀야 하는데 겉모습이 갈리면
 * 사람은 그 차이를 뜻으로 읽는다. 그래서 값은 여기 한 곳에만 둔다.
 *
 * ── 왜 dashboard/ 가 아니라 common/ 인가 ────────────────────────────────
 * 원래 이 파일은 `components/dashboard/weekly-report-note-button.ts` 였다.
 * 내자 정리(`components/domestic-orders/`)가 같은 겉모습을 쓰게 되면서, 한
 * 화면의 폴더 안에 있는 파일을 다른 화면이 가져다 쓰는 모양이 되었다 — 그러면
 * 이름이 "주간보고 것"이라고 말하는데 실제로는 아니어서, 나중에 주간보고를
 * 고치는 사람이 이 값을 자기 것으로 알고 바꾼다. 옮기면서 **값은 한 글자도
 * 바꾸지 않았다**(주간보고 두 칸의 결과 마크업이 달라지면 안 된다).
 *
 * 이 파일이 컴포넌트가 아니라 값 두 개뿐인 것은 일부러다. 이 칸들은 **저장하는
 * 길이 서로 다르다** — 주간보고 상세표는 수리 건의 notes 를
 * (updateRepairCaseAction), 납입 예정 건은 그 줄의 note 를
 * (updateWeeklyReportDeliveryAction), 내자 정리는 그 줄 전체를
 * (updateDomesticOrderAction) 고친다. 편집칸도 textarea 와 input 으로 갈린다
 * (각 파일의 주석). 공통인 것은 **안 고칠 때 보이는 글자의 겉모습**뿐이라,
 * 나눠 쓰는 것도 딱 그만큼이어야 한다. 억지로 한 컴포넌트로 묶으면 서로 다른
 * 저장 경로가 한 파일에 얽힌다.
 * ============================================================================
 */

/**
 * 이 버튼이 글자를 **어떻게 접는가**. 부르는 쪽이 반드시 골라야 한다.
 *
 * - `whitespace-pre-line` — 값에 실제로 줄바꿈이 들어 있는 칸(주간보고 두 비고).
 *   `<td>` 의 같은 성질이 폼 컨트롤 안까지 내려온다는 보장이 없어 버튼에 다시
 *   적는다 — 여러 줄 비고의 줄바꿈이 이 칸에서만 사라지면 안 된다.
 * - `whitespace-nowrap` — 한 줄짜리 값이라 접히면 안 되는 칸(내자 정리 다섯).
 * - `whitespace-pre` — 사람이 친 줄바꿈에서**만** 끊고 폭이 모자라도 접지 않는
 *   칸(내자 정리 **표**의 현황·이력·기타). 왜 pre-line 이 아닌지는
 *   DomesticOrderListScreen 의 noteCellContentClass 에 적혀 있다 — 요약하면
 *   화면에 보이는 줄바꿈의 근거가 "사람이 친 것" 하나뿐이어야 해서다.
 * - `break-words whitespace-pre-line` — 같은 값을 **카드**에서 그릴 때. 폰에서
 *   좌우 스크롤은 사실상 못 쓰는 조작이라 폭이 모자라면 접어야 한다. 표와
 *   카드가 일부러 다른 자리이고, 그 까닭도 같은 파일에 있다.
 * - `break-words whitespace-normal` — 카드에서 **아직 줄바꿈을 살리지 않는**
 *   여러 줄 칸(내자 정리 카드의 고장내역). 눌러서 고칠 수 있게 되었어도 안 고칠
 *   때 보이는 글자는 지금까지와 한 글자도 달라지면 안 된다.
 *
 * ⚠️ 뒤 두 가지에 `break-words` 가 **함께** 들어 있는 것은 일부러다. 카드의
 * `<dd>` 가 이미 break-words 를 걸고 있지만, 위 pre-line 을 버튼에 다시 적는
 * 것과 같은 이유로 — 그 성질이 폼 컨트롤 안까지 내려온다는 보장이 없다 — 이
 * 버튼이 자기 것을 선언한다. 접는 방식은 한 자리에서 통째로 정해져야, 어느 쪽이
 * 상속되고 어느 쪽이 선언인지 나중에 읽는 사람이 헷갈리지 않는다.
 *
 * 값을 세는 타입인 것은 일부러다. **고르지 않고 부를 수 없어야** 아래 함수
 * 주석이 말하는 규칙이 말로만 남지 않는다. 다른 성질이 필요한 칸이 생기면 그때
 * 여기에 한 줄 늘리면 된다 — 그것도 "이 칸의 값은 어떤 성질인가"를 한 번 생각하고
 * 지나가는 자리다.
 *
 * 이름이 `…Whitespace` 가 아니라 `…Wrapping` 인 것은 값 두 개가 white-space 만으로
 * 이루어져 있지 않기 때문이다. 이 인자가 정하는 것은 처음부터 **접는 방식**이었다.
 */
export type InlineEditCellWrapping =
  | "whitespace-pre-line"
  | "whitespace-nowrap"
  | "whitespace-pre"
  | "break-words whitespace-pre-line"
  | "break-words whitespace-normal";

/**
 * 안 고칠 때 보여 주는 글자 자체를 감싸는 `<button type="button">` 의 겉모습.
 *
 * 겉모습은 **평범한 글자 그대로**다(테두리도 배경도 없다) — 버튼처럼 보이게 하면
 * 버튼을 없앤 뜻이 사라진다.
 *
 * - `-mx-1 px-1` 은 짝이다: hover 배경만 글자 밖으로 조금 넓히고 글자가 서는
 *   자리는 그대로 둔다. 넓히기만 하면 이 칸의 글자만 오른쪽으로 밀려 표의
 *   세로줄이 어긋난다.
 * - `w-full` + `text-left` — 값이 비면 화면에 `-` **한 글자뿐**이라, 글자에만
 *   걸면 누를 곳이 점 하나가 된다. 칸의 폭은 채우되 글자는 표의 다른 칸과 같은
 *   자리에서 시작해야 한다.
 *
 * ── ⚠️ 줄바꿈 처리만은 여기서 정하지 않는다 ─────────────────────────────
 * 예전에는 이 문자열 안에 `whitespace-pre-line` 이 박혀 있었다. 주간보고 비고를
 * 위한 값이었는데, 내자 정리 다섯 칸이 같은 겉모습을 나눠 쓰면서 **그 성질까지
 * 따라왔다** — 발주서번호·PJT·견적서번호·납품자·일본 송금은 한 줄짜리 값인데
 * 칸 너비에 갇혀 접혔다. 표의 `<tr>` 이 `whitespace-nowrap` 이어도 소용없다.
 * 버튼 자신의 선언이 상속을 이기기 때문이다.
 *
 * **쓰는 곳마다 값의 성질이 다르다** — 주간보고 비고에는 실제로 여러 줄이 들어
 * 있고, 내자 정리 다섯 칸은 한 줄이다. 그래서 줄바꿈 처리는 공용 값이 정할 수
 * 있는 것이 아니고, 부르는 쪽이 인자로 넘긴다.
 *
 * 뒤에 **덧붙여 덮어쓰지 않고 아예 뺀 이유**: `whitespace-pre-line` 과
 * `whitespace-nowrap` 은 **같은 Tailwind 그룹**이라 한 declaration 을 놓고 다툰다.
 * 클래스 속성에 늦게 적는다고 이기는 것이 아니라 **만들어진 CSS 안의 차례**가
 * 정한다 — 즉 덧붙이기는 이기는 것처럼 보여도 실제로는 운에 맡기는 것이고,
 * 유틸리티 순서가 바뀌는 날 조용히 뒤집힌다. 지금 없으니 다툴 일 자체가 없다.
 *
 * **이 값을 새로 쓰는 곳은 줄바꿈 처리를 반드시 자기가 정해야 한다.** 인자를
 * 빼먹을 수 없게 타입으로 막아 두었다(위 InlineEditCellWrapping).
 *
 * ⚠️ **relative 를 빼지 말 것.** 이 버튼 안에는 낭독기용 sr-only 조각이 하나
 * 들어가는데 Tailwind 의 sr-only 는 `position: absolute` 다. 기준이 되는 위치
 * 지정 조상이 없으면 그 span 이 AppShell `<main>` 의 자르기를 빠져나가 **문서
 * 바닥에 자리를 주장한다.** 그러면 `<main>` 스크롤과 별개로 창 스크롤이 하나 더
 * 생기고, 그것을 내리면 파란 헤더와 사이드바까지 밀려 올라간다 — 이 저장소가
 * 실제로 겪은 고장이고 높이가 1px 이라 눈으로도 진단으로도 안 걸린다(경위는
 * WeeklyReportGoalsPanel 의 GoalPrefix 주석). 이 값을 쓰는 표들은 줄이 수백
 * 개까지 가는 자리라 같은 고장을 그 수만큼 되살릴 수 있다. relative 는 좌표를
 * 주지 않으면 아무것도 옮기지 않고 z-index:auto 라 쌓임 맥락도 만들지 않는다.
 *
 * ⚠️ 인자가 들어가는 자리는 `whitespace-pre-line` 이 **예전에 서 있던 그 자리**다.
 * `inlineEditCellButtonClass("whitespace-pre-line")` 이 예전 문자열과 한 글자도
 * 다르지 않아야, 주간보고 두 칸의 마크업이 이 변경으로 흔들리지 않았다는 것을
 * 문자열 대조만으로 말할 수 있다.
 */
export function inlineEditCellButtonClass(wrapping: InlineEditCellWrapping): string {
  return `relative -mx-1 block w-full cursor-pointer rounded px-1 text-left ${wrapping} hover:bg-zinc-100 focus-visible:ring-2 focus-visible:ring-zinc-400 focus-visible:outline-none dark:hover:bg-zinc-800 dark:focus-visible:ring-zinc-500`;
}

/**
 * 목적격 조사 을/를. 한글 음절의 **받침 유무**로 정한다.
 *
 * 가~힣(U+AC00~U+D7A3)은 (초성·중성·종성)을 28 로 묶어 배열한 영역이라,
 * `(코드 - 0xAC00) % 28` 이 0 이면 받침이 없다. 표를 들고 있을 필요가 없다.
 *
 * 한글이 아닌 글자로 끝나면(`PJT` 처럼 라틴 문자 칸 이름이 실제로 있다) 받침을
 * 알 길이 없으므로 `를` 로 둔다 — 알파벳을 한국어로 읽었을 때(티 · 씨 · 이 …)
 * 받침으로 끝나는 것은 L · M · N 뿐이라, 모르는 경우의 기본값으로는 `를` 이
 * 맞을 확률이 훨씬 높다.
 */
function objectParticle(label: string): "을" | "를" {
  const trimmed = label.trim();
  const code = trimmed.length === 0 ? Number.NaN : trimmed.charCodeAt(trimmed.length - 1);
  if (!(code >= 0xac00 && code <= 0xd7a3)) return "를";
  return (code - 0xac00) % 28 === 0 ? "를" : "을";
}

/**
 * 마우스를 올려 두면 뜨는 글자. `수정` 글자가 사라진 자리를 메우는 단서 셋 중
 * 하나다 — 장식으로 오해해 걷어내면 그만큼 못 찾는 사람이 생긴다.
 *
 * 예전에는 `클릭하면 비고를 고칠 수 있습니다` 라는 **문자열 하나**였다. 이제
 * 비고 전용이 아니므로 칸 이름을 받아 만든다 — 어느 칸을 눌렀는지 말해 주지
 * 못하면, 한 줄에 누를 수 있는 칸이 다섯인 표(내자 정리)에서 이 안내는 아무것도
 * 알려 주지 않는 말이 된다.
 *
 * ⚠️ `inlineEditCellButtonTitle("비고")` 는 **예전 문자열과 한 글자도 다르지
 * 않아야 한다**(주간보고 두 칸이 지금 쓰는 문구). 조사를 붙이는 규칙이 위에
 * 따로 있는 이유가 그것이다 — `비고을` 이 되면 옮기기가 화면을 바꾼 것이 된다.
 */
export function inlineEditCellButtonTitle(label: string): string {
  return `클릭하면 ${label}${objectParticle(label)} 고칠 수 있습니다`;
}
