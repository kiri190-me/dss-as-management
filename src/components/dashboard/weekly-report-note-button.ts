/**
 * ============================================================================
 * 주간보고 `비고` 칸을 여는 글자의 겉모습 — 두 표가 **나눠 쓰는** 값
 * ============================================================================
 * 주간보고 한 화면에는 `비고` 칸이 둘 있다 — 위 고객사 상세표의 칸
 * (WeeklyReportNotesCell)과 맨 아래 납입 예정 건 표의 칸
 * (WeeklyReportDeliveriesPanel 의 DeliveryLine). 둘 다 `수정` 버튼 없이 **칸을
 * 누르면 곧바로 편집으로 들어간다** — 한 화면에 비고가 둘인데 하나만 눌러서
 * 열리면 오히려 더 헷갈린다는 것이 그렇게 정한 이유다(사용자 결정).
 *
 * ── 왜 값을 이 파일 한 곳에 두는가 ──────────────────────────────────────
 * `수정` 이라는 글자가 사라졌으므로, **단서가 없으면 여기를 고칠 수 있다는 사실을
 * 아무도 모른다.** 그 자리를 메우는 것이 아래 두 값이다 — hover 배경과 손가락
 * 커서(마우스), focus-visible 테두리(키보드로 훑는 사람에게는 이것이 유일한
 * 단서다), 그리고 올려 두면 뜨는 title. 까닭은 WeeklyReportNotesCell 헤더에
 * 자세히 적혀 있다.
 *
 * 이 문자열을 두 파일에 각각 적으면 **언젠가 한쪽만 고쳐진다.** 그 순간 같은
 * 화면의 두 비고가 다르게 보이고, 그러면 애초에 버튼을 없앤 뜻이 사라진다 —
 * "이 화면의 비고는 눌러서 고친다"가 한 가지 규칙으로 읽혀야 하는데 겉모습이
 * 갈리면 사람은 그 차이를 뜻으로 읽는다. 그래서 값은 여기 한 곳에만 둔다.
 *
 * 이 파일이 컴포넌트가 아니라 문자열 두 개뿐인 것은 일부러다. 두 칸은 **저장하는
 * 길이 서로 다르다** — 상세표는 수리 건의 notes 를(updateRepairCaseAction), 납입
 * 예정 건은 그 줄의 note 를(updateWeeklyReportDeliveryAction) 고친다. 편집칸도
 * 한쪽은 textarea 고 한쪽은 input 이다(각 파일의 주석). 공통인 것은 **안 고칠 때
 * 보이는 글자의 겉모습**뿐이라, 나눠 쓰는 것도 딱 그만큼이어야 한다. 억지로 한
 * 컴포넌트로 묶으면 서로 다른 두 저장 경로가 한 파일에 얽힌다.
 * ============================================================================
 */

/**
 * 안 고칠 때 보여 주는 글자 자체를 감싸는 `<button type="button">` 의 겉모습.
 *
 * 겉모습은 **평범한 글자 그대로**다(테두리도 배경도 없다) — 버튼처럼 보이게 하면
 * 버튼을 없앤 뜻이 사라진다.
 *
 * - `-mx-1 px-1` 은 짝이다: hover 배경만 글자 밖으로 조금 넓히고 글자가 서는
 *   자리는 그대로 둔다. 넓히기만 하면 이 칸의 글자만 오른쪽으로 밀려 표의
 *   세로줄이 어긋난다.
 * - `w-full` + `text-left` — 비고가 비면 화면에 `-` **한 글자뿐**이라, 글자에만
 *   걸면 누를 곳이 점 하나가 된다. 칸의 폭은 채우되 글자는 표의 다른 칸과 같은
 *   자리에서 시작해야 한다.
 * - `whitespace-pre-line` 을 여기 다시 적는 것은 `<td>` 의 그것이 폼 컨트롤
 *   안까지 내려온다는 보장이 없어서다 — 여러 줄 비고의 줄바꿈이 이 칸에서만
 *   사라지면 안 된다.
 *
 * ⚠️ **relative 를 빼지 말 것.** 이 버튼 안에는 낭독기용 sr-only 조각이 하나
 * 들어가는데 Tailwind 의 sr-only 는 `position: absolute` 다. 기준이 되는 위치
 * 지정 조상이 없으면 그 span 이 AppShell `<main>` 의 자르기를 빠져나가 **문서
 * 바닥에 자리를 주장한다.** 그러면 `<main>` 스크롤과 별개로 창 스크롤이 하나 더
 * 생기고, 그것을 내리면 파란 헤더와 사이드바까지 밀려 올라간다 — 이 저장소가
 * 실제로 겪은 고장이고 높이가 1px 이라 눈으로도 진단으로도 안 걸린다(경위는
 * WeeklyReportGoalsPanel 의 GoalPrefix 주석). 이 값을 쓰는 두 표는 줄이 수백
 * 개까지 가는 자리라 같은 고장을 그 수만큼 되살릴 수 있다. relative 는 좌표를
 * 주지 않으면 아무것도 옮기지 않고 z-index:auto 라 쌓임 맥락도 만들지 않는다.
 */
export const noteCellButtonClass =
  "relative -mx-1 block w-full cursor-pointer rounded px-1 text-left whitespace-pre-line hover:bg-zinc-100 focus-visible:ring-2 focus-visible:ring-zinc-400 focus-visible:outline-none dark:hover:bg-zinc-800 dark:focus-visible:ring-zinc-500";

