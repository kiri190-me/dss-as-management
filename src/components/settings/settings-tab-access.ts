/**
 * ============================================================================
 * [시스템 설정]의 탭 둘 — 차례와 이름 (2026-11-13)
 * ============================================================================
 * 2026-11-13 까지 이 화면에는 카드가 하나뿐이었다(고객 안내 상태 목록). 「배지
 * 표시」가 들어오면서 탭이 생겼고, 본보기는 [사용자 관리]의 탭 다섯
 * (components/users/users-tab-access.ts)이다 — 차례·이름·「처음 보여 줄 탭」을
 * **순수 모듈 하나**가 쥐고, 화면은 그것을 늘어놓기만 한다.
 *
 * 🔴 **조건을 JSX 에 흩어 두지 않는다.** 흩어 두면 탭 단추와 탭 내용과 「첫 탭은
 * 무엇인가」가 각자 따지게 되고, 그때 생기는 어긋남이 「단추는 없는데 그 내용이
 * 그려진다」(또는 그 반대)다. 순수 함수라 값으로 잴 수 있는 것도 그래서다 — 화면
 * 본체는 서버 액션을 가져오는 클라이언트 컴포넌트라 시험에서 렌더할 수 없다.
 *
 * ── 🔴 [사용자 관리]와 다른 점: **여닫는 조건이 없다** ──────────────────
 * 저쪽은 권한에 따라 탭이 사라진다(자료를 아예 안 내려보내므로 「감추는 것이 아니라
 * 없는 것」이다). 여기는 둘 다 **늘 보인다**:
 *  · 두 탭이 보여 주는 것은 **설정의 현재 값**이고, 이 화면에 들어온 사람은 이미
 *    `settings` 읽기를 가진 사람이다(app/(app)/settings/page.tsx 의 관문).
 *  · 권한이 가르는 것은 탭 **안의 고치기**다 — 못 고치는 사람에게도 지금 무엇이
 *    꺼져 있는지는 보여야 한다. 끈 배지를 찾으러 오는 사람이 탭조차 못 보면,
 *    관리자에게 "뭐가 꺼져 있나요"를 물어보는 수밖에 없다.
 * 그래서 이 파일에는 `visibleTabKeys` 같은 거르개가 없다. 🔵 조건이 생기는 날
 * 저쪽(users-tab-access.ts)의 모양을 그대로 가져오면 된다 — 그때 「처음 보여 줄
 * 탭」은 **보이는 것 가운데 첫째**여야 한다(저쪽이 적어 둔 함정).
 * ============================================================================
 */

/** 🔴 **차례가 곧 탭 줄의 차례**다. */
export const SETTINGS_TAB_KEYS = ["customerStatusOptions", "badgeVisibility"] as const;

export type SettingsTabKey = (typeof SETTINGS_TAB_KEYS)[number];

/** 탭 단추에 적히는 말. 🔴 탭 안의 묶음 제목과 **같은 글자**여야 한다. */
export const SETTINGS_TAB_LABELS: Record<SettingsTabKey, string> = {
  customerStatusOptions: "고객 안내 상태 목록",
  badgeVisibility: "배지 표시",
};

/**
 * 화면을 열었을 때 처음 보여 줄 탭.
 *
 * 🔴 **첫째가 「고객 안내 상태 목록」이어야 한다.** 탭이 생기기 전까지 이 화면에
 * 들어오던 사람이 보던 것이 그 카드다 — 둘째를 기본으로 두면, 늘 하던 일을 하러 온
 * 사람이 처음 보는 화면에서 제 카드를 못 찾는다.
 */
export function initialSettingsTab(): SettingsTabKey {
  return SETTINGS_TAB_KEYS[0];
}
